def run_closure_lines(P, run, R):
    """Lines of the root import closure before and after a run; computed from the export and the run's
    deletion list when the run did not record it, and kept in runs/<run>/closure_lines.json."""
    if 'rootImportClosure' in R.get('sizes', {}):
        return R['sizes']['rootImportClosure']
    rdir = os.path.join(P.out, 'runs', run)
    cp, dp = os.path.join(rdir, 'closure_lines.json'), os.path.join(rdir, 'deleted.json')
    if os.path.exists(cp):
        return json.load(open(cp))
    if not os.path.exists(dp):
        return None
    C = Corpus(P)
    K = classify(C)
    cl = closure_lines(C, K, set(json.load(open(dp))), K['keep_files'] | set(R.get('filesRestoredAsTargets', [])))
    json.dump(cl, open(cp, 'w'), indent=1)
    return cl



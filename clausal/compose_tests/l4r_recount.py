#!/usr/bin/env python3
"""ARM A1 ON THE 48, COUNTED AGAIN BY WHAT EACH "RIGHT" RESTS ON (fix round of plan node L1c). Reads committed results;
runs no composer.

    python3 clausal/compose_tests/l4r_recount.py [DIR]            # DIR: l4r_a1 (default) or l4r_a1_sens; writes DIR/RECOUNT.md
    tools/sem.sh 3 -- python3 clausal/compose_tests/l4r_recount.py --a0 $S/clausal
                                                                  # the oracle author over version 1's three candidates (Lean);
                                                                  # $S/clausal: a scratch copy (mutation/workcopy.sh); writes l4r_a1/a0_oracle.json

WHY. The report of arm A1 (l4r_a1/REPORT.md, generated by l4r.py, frozen) puts "right after questions: 9" beside A0's 0.
A reviewer pointed out two things the row does not say:
 (a) HOW the nine end. The oracle author is shown lists of candidates and picks the one that is the gold reading (the same
     Lean term, or proved equal). All nine end with such a pick. So the row counts "the gold reading, or a sentence proved
     equal to it, is among the candidates shown within three questions". Version 1 (A0) was never given an author who
     picks: its 0 is "it asks nothing", not "the gold was not among its candidates".
 (b) BY WHICH STANDARD. "Answered right" (A1) and TOP-RIGHT (A0) mean RIGHT on the author's cases: every encodable case
     agrees. "Right after questions" means AT THE GOLD READING. A gold reading can be other than RIGHT on the cases
     (SCOPE-DIFFERS: a case the author calls "holds" where the narrowed gold is silent).

WHAT IS COUNTED HERE, all from DIR/results.json and compose_tests/l4b_a0/results.json:
  per "right after questions" sentence: its turns, whether the last is a pick from a list, how many candidates were put
      before the oracle in all, and what the sentence it ends with is on the author's cases.
  A1 by the cases standard: answered right (alone) + right after questions whose final sentence is RIGHT on the cases.
  A0 by the cases standard with a pick allowed: TOP-RIGHT + RIGHT-IN-TOP-3 (a candidate of its three is RIGHT).
  A0 by the gold standard (--a0): for each sentence with a gold reading, dialogue.Oracle.is_gold over the three candidates
      of the committed A0 run: is the first the gold reading (no pick), is one of the three (a pick). This is the nearest
      like-for-like there is; it is still not the same test: A1's oracle is shown up to three lists (after "none of these"
      the next candidates), A0's three are all that the committed run kept.
Nothing here changes a tally of l4r.py; its definitions stay as frozen.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
A0 = HERE / "l4b_a0" / "results.json"
A0_ORACLE = HERE / "l4r_a1" / "a0_oracle.json"
PICKS = ("accept", "which")


def a0_main(work: Path) -> int:
    assert (work / "clausal" / "compose2.py").exists(), f"no scratch copy of clausal/ at {work} (see the usage)"
    sys.path.insert(0, str(work))
    import os
    os.chdir(work)
    from clausal import dialogue
    gold = json.loads((HERE / "l4r_a1" / "gold.json").read_text())["gold"]
    a1 = {r["key"]: r for r in json.loads((HERE / "l4r_a1" / "results.json").read_text())["rows"]}
    rows, t0, lean = [], time.time(), 0
    for r in json.loads(A0.read_text())["rows"]:
        g = (gold.get(r["key"]) or {}).get("sentence")
        if not g:
            continue
        orc = dialogue.Oracle([g], a1[r["key"]]["sentences"]["gold"]["system"])
        vs = orc.is_gold([{"sentence": c["sentence"], "system": c["system"]} for c in r["candidates"]])
        lean += orc.lean_runs
        rows.append({"key": r["key"], "gold": g, "a0_outcome": r["outcome"],
                     "candidates": [{"rank": c["rank"], "sentence": c["sentence"], "system": c["system"], "on_the_cases": c["kind"], "against_gold": v["verdict"]}
                                    for c, v in zip(r["candidates"], vs)]})
        print(r["key"], [v["verdict"] for v in vs], file=sys.stderr, flush=True)
    eq = ("SAME-TERM", "PROVED-EQUAL")
    res = {"schema": "l4r-a0-oracle-v1", "date": time.strftime("%Y-%m-%d"),
           "what": "the three candidates of the committed A0 run (compose_tests/l4b_a0/results.json) against the gold readings of arm A1 "
                   "(l4r_a1/gold.json), by dialogue.Oracle.is_gold: the same Lean term, or proved equal by Lean's kernel. No composer is run",
           "with_gold": len(rows), "lean_runs": lean, "seconds": round(time.time() - t0, 1),
           "top_is_gold": sorted(r["key"] for r in rows if r["candidates"] and r["candidates"][0]["against_gold"] in eq),
           "gold_in_top_3": sorted(r["key"] for r in rows if any(c["against_gold"] in eq for c in r["candidates"])),
           "rows": rows}
    A0_ORACLE.write_text(json.dumps(res, indent=1, ensure_ascii=False) + "\n")
    print(f"A0 against the gold readings ({len(rows)} sentences with one): the top candidate is the gold reading for {len(res['top_is_gold'])}; "
          f"the gold reading is among the three for {len(res['gold_in_top_3'])}")
    return 0


def recount(d: dict) -> dict:
    rows = d["rows"]
    raq = []
    for r in rows:
        if r["cell"] != "right after questions":
            continue
        x = r["A1d"]
        turns = x["turns"]
        raq.append({"key": r["key"], "end": x["end"], "questions": x["questions"], "turns": [[t["kind"], t["answer"]] for t in turns],
                    "last_turn_is_a_pick": bool(turns) and turns[-1]["kind"] in PICKS and turns[-1]["answer"] is not None,
                    "candidates_put_before_the_oracle": sum(len(t["shown"]) for t in turns if t["kind"] in PICKS),
                    "against_gold": x["against_gold"], "on_the_cases": r["sentences"]["A1d"]["kind"], "gold_on_the_cases": r["sentences"]["gold"]["kind"]})
    alone = [r for r in rows if r["A1"]["outcome"] == "ANSWER"]
    with_gold = [r for r in rows if r["gold"]]
    unresolved = [r for r in with_gold if (r.get("A1d") or {}).get("end") == "UNRESOLVED"]
    out = {"right_after_questions": raq,
           "raq_by_cases": {k: sorted(x["key"] for x in raq if x["on_the_cases"] == k) for k in sorted({x["on_the_cases"] for x in raq})},
           "raq_end_with_a_pick": sum(x["last_turn_is_a_pick"] for x in raq),
           "raq_last_turn_kinds": {k: sum(x["turns"][-1][0] == k for x in raq if x["turns"]) for k in ("accept", "which", "input", "system", "operation")},
           "answered_alone": {"n": len(alone), "RIGHT_on_cases": sorted(r["key"] for r in alone if r["sentences"]["A1"]["kind"] == "RIGHT"),
                              "at_gold": sorted(r["key"] for r in alone if r["A1"].get("against_gold") in ("SAME-TERM", "PROVED-EQUAL"))},
           "with_gold": len(with_gold),
           "at_gold": sorted(r["key"] for r in with_gold if (r.get("A1d") or {}).get("at_gold")),
           "unresolved_candidates_shown": {r["key"]: sum(len(t["shown"]) for t in r["A1d"]["turns"] if t["kind"] in PICKS) for r in unresolved}}
    out["A1_right_on_cases_with_questions"] = sorted(out["answered_alone"]["RIGHT_on_cases"] + out["raq_by_cases"].get("RIGHT", []))
    if A0.exists() and len(rows) == 48:
        a0 = json.loads(A0.read_text())
        out["A0_cases"] = a0["counts"]
        out["A0_top_right"] = sorted(r["key"] for r in a0["rows"] if r["outcome"] == "TOP-RIGHT")
        out["A0_right_in_top_3"] = sorted(r["key"] for r in a0["rows"] if r["outcome"] == "RIGHT-IN-TOP-3")
    if A0_ORACLE.exists() and len(rows) == 48:
        o = json.loads(A0_ORACLE.read_text())
        out["A0_gold"] = {"with_gold": o["with_gold"], "top_is_gold": o["top_is_gold"], "gold_in_top_3": o["gold_in_top_3"]}
    return out


def report(name: str, d: dict, c: dict) -> str:
    raq = c["right_after_questions"]
    o = [f"# `{name}`: what each \"right\" rests on", "",
         f"Generated by `clausal/compose_tests/l4r_recount.py {name}` from `{name}/results.json`; do not edit. It adds no run and changes no tally; "
         "it says what the row \"right after questions\" counts and puts both standards side by side. CONTAMINATED like the run it reads.", "",
         f"## The {len(raq)} \"right after questions\"", "",
         "| Sentence | Turns (kind -> answer) | Ends with a pick from a list | Candidates put before the oracle | Against gold | Final sentence on the author's cases |",
         "|---|---|---|---|---|---|"]
    for x in raq:
        o.append(f"| `{x['key']}` | {'; '.join(f"{k} -> {'none' if a is None else a}" for k, a in x['turns'])} | "
                 f"{'yes' if x['last_turn_is_a_pick'] else 'NO'} | {x['candidates_put_before_the_oracle']} | {x['against_gold']} | {x['on_the_cases']} |")
    k = c["raq_last_turn_kinds"]
    o += ["", f"- **All end with a pick: {c['raq_end_with_a_pick']} of {len(raq)}** (last turn: accept {k['accept']}, which {k['which']}, input {k['input']}). "
              "The oracle author is shown a list and names the candidate that is the gold reading (the same term, or proved equal). No sentence of the row "
              "was reached by a question about an input. The row therefore counts: *the gold reading, or a sentence proved equal to it, is among the "
              "candidates shown within three questions*.",
          "- **By the cases standard** (the one used for \"answered right\" and for A0's TOP-RIGHT: every encodable case agrees): "
          + "; ".join(f"{kind} {len(v)} ({', '.join(v)})" for kind, v in c["raq_by_cases"].items()) + ". A sentence at the gold reading that is "
          "SCOPE-DIFFERS on the cases has a case its author calls \"holds\" where the gold reading is silent (out of its scope).", "",
          "## The two standards side by side", "",
          "| | A1 (version 2 + oracle author) | A0 (version 1) |", "|---|---|---|"]
    a = c["answered_alone"]
    a0c, a0g = c.get("A0_cases"), c.get("A0_gold")
    o.append(f"| RIGHT on the cases, no question, no pick | {len(a['RIGHT_on_cases'])} | {a0c['TOP-RIGHT'] if a0c else 'n/a'} (TOP-RIGHT) |")
    o.append(f"| RIGHT on the cases, a pick allowed | {len(c['A1_right_on_cases_with_questions'])} (alone {len(a['RIGHT_on_cases'])} + after questions {len(c['raq_by_cases'].get('RIGHT', []))}; "
             f"up to three lists) | {a0c['TOP-RIGHT'] + a0c['RIGHT-IN-TOP-3'] if a0c else 'n/a'} (TOP-RIGHT + RIGHT-IN-TOP-3; one list of three) |")
    o.append(f"| At the gold reading, no question, no pick (of {c['with_gold']} with a gold reading) | {len(a['at_gold'])} | "
             + (f"{len(a0g['top_is_gold'])} |" if a0g else "not measured (run `l4r_recount.py --a0`) |"))
    o.append(f"| At the gold reading, a pick allowed (of {c['with_gold']}) | {len(c['at_gold'])} (up to three lists) | "
             + (f"{len(a0g['gold_in_top_3'])} (one list of three) |" if a0g else "not measured (run `l4r_recount.py --a0`) |"))
    o += ["", "- \"A pick allowed\" for A0 is what an oracle author would get from version 1's three candidates. It is the nearest like-for-like to "
              "\"right after questions\" and it is not the same test: the dialogue shows further candidates after \"none of these\" (up to three lists), "
              "and the committed A0 run kept three candidates per sentence.",
          "- A1 answers alone for " + str(a["n"]) + " sentences and asks for the rest; A0 gives its top candidate for all 48. The rows above count "
          "right outcomes only; the wrong answers are in the reports of the runs."]
    if a0g:
        o.append(f"- A0, top candidate at the gold reading: {', '.join(a0g['top_is_gold']) or 'none'}. Gold among its three: {', '.join(a0g['gold_in_top_3']) or 'none'}.")
    o.append(f"- A1 at the gold reading: {', '.join(c['at_gold'])}.")
    u = c["unresolved_candidates_shown"]
    if u:
        o += ["", f"Unresolved after three questions: {len(u)}; candidates put before the oracle in those dialogues: "
                  + ", ".join(f"`{k}` {v}" for k, v in sorted(u.items())) + "."]
    return "\n".join(o)


if __name__ == "__main__":
    if "--a0" in sys.argv:
        sys.exit(a0_main(Path(sys.argv[sys.argv.index("--a0") + 1]).resolve()))
    name = sys.argv[1] if len(sys.argv) > 1 else "l4r_a1"
    d = json.loads((HERE / name / "results.json").read_text())
    c = recount(d)
    (HERE / name / "recount.json").write_text(json.dumps(c, indent=1, ensure_ascii=False) + "\n")
    text = report(name, d, c)
    (HERE / name / "RECOUNT.md").write_text(text + "\n")
    print(text)

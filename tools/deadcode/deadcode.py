def name_matches(tok, user):
    a, b = tok.split('.'), user.split('.')
    k = min(len(a), len(b))
    return a[-k:] == b[-k:]


UNKNOWN_RE = re.compile(r"^(?:Unknown (?:identifier|constant)|unknown (?:identifier|constant)|Invalid field)")


def attribute_by_name(C, m, msgs, dele, quoted_only):
    """Deleted declarations that an error message names.  A printed term can only contain constants that
    still exist, so an identifier equal to a deleted declaration's name is an unresolved reference.
    An "unknown identifier" whose name is that of a declaration that STAYS in this file is a cascade (that
    declaration failed to elaborate earlier in the file) and is not attributed.  Returns (hits, explained):
    the declarations and the indices of the messages they or a cascade account for."""
    vis = (C.import_closure(m) | {m}) if m in C.pimports else set(C.modules)   # a file outside the analysed modules sees all
    idx = collections.defaultdict(list)
    for n in dele:
        if C.by[n]['module'] in vis:
            idx[C.by[n]['userName'].split('.')[-1]].append(n)
    kept_here = collections.defaultdict(list)
    for d in C.bymod.get(m, []):
        if d['name'] not in dele:
            kept_here[d['userName'].split('.')[-1]].append(d)
    hits, explained = {}, set()
    for k, e in enumerate(msgs):
        if quoted_only:
            toks = re.findall(r'`([^`\s]+)`', e['msg'])
            # with `autoImplicit`, an unknown name becomes a variable and the error is about its use:
            # "Function expected at\n  Foo\nbut this term has type ?m.3"
            mm = re.match(r'Function expected at\s*\n\s*([^\s()]+)\s*\nbut this term has type\s*\n?\s*\?', e['msg'])
            if mm:
                toks.append(mm.group(1))
        else:
            toks = re.findall(r"[A-Za-z_À-￿][\w.'!?À-￿]*", e['msg'])
        for t in toks:
            t = t.lstrip('@').rstrip('.✝')
            last = t.split('.')[-1]
            if not quoted_only and len(last) < 4 and '.' not in t:
                continue
            ol = e.get('origLine', e['line'])
            if any(name_matches(t, d['userName']) and d['line'] <= ol for d in kept_here.get(last, [])):
                if UNKNOWN_RE.match(e['msg']):
                    explained.add(k)
                continue
            for n in idx.get(last, []):
                if name_matches(t, C.by[n]['userName']):
                    hits.setdefault(n, e)
                    explained.add(k)
    return hits, explained


TRACE_PATS = (('trace.Meta.Tactic.simp.rewrite', re.compile(r'\[Meta\.Tactic\.simp\.rewrite\] (?:unfold )?@?([^\s:,]+)')),
              ('trace.Meta.synthInstance', re.compile(r'apply @?([^\s:,]+) to ')))


def attribute_by_trace(P, C, pristine, m, orig_lines, dele, logdir, tag):
    """Ask Lean which simp lemmas / instances the ORIGINAL file used in the declarations that now fail:
    elaborate the pristine module once with simp-rewrite and instance-synthesis traces switched on, read the
    trace as it is printed, and intersect the names with the deleted set.  One `lake lean` run of one
    module in the untouched copy; nothing is rebuilt."""
    vis = C.import_closure(m) | {m}
    idx = collections.defaultdict(list)
    for n in dele:
        if C.by[n]['module'] in vis:
            idx[C.by[n]['userName'].split('.')[-1]].append(n)
    # The trace prints names as the file's open namespaces abbreviate them, so a name is matched by its
    # trailing components.  A deleted declaration is a candidate only if simp or instance search could have
    # used it without leaving it in a term (table entry, or named in kept source), and a printed name that
    # also fits a declaration that stays is not attributed at all.
    kept_last = collections.defaultdict(list)
    for mm in vis:
        for d in C.bymod.get(mm, []):
            if d['name'] not in dele:
                kept_last[d['userName'].split('.')[-1]].append(d['userName'])
    eligible = set(n for n in dele if C.attr_tags(C.by[n]) or C.S_users.get(n))
    ranges = []
    for ol in orig_lines:
        c = [C.drange(d) for d in C.bymod.get(m, []) if C.drange(d)[0] <= ol <= C.drange(d)[1]]
        ranges.append(min(c, key=lambda r: r[1] - r[0]) if c else (ol, ol))
    rel = os.path.relpath(P.mpath(pristine, m), pristine)
    cache = os.path.join(logdir, '%s_trace.json' % tag)
    if os.path.exists(cache):
        j = json.load(open(cache))
        if j.get('ranges') == [list(r) for r in ranges] and j.get('exit') == 0 and 'detail' in j:
            return {n: v for n, v in j['detail'].items() if n in dele}
    hits = {}
    t0 = time.time()
    stages = []
    # simp first: the instance trace of a large file is very large, and is only asked for when simp explains nothing
    for opt, pat in TRACE_PATS:
        cmd = ['lake', 'lean', rel, '--', '--json', '-D', opt + '=true']
        nlines = 0
        pr = subprocess.Popen(cmd, cwd=pristine, env=P.env(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              text=True, errors='replace')
        try:
            for l in pr.stdout:
                nlines += 1
                # `lean --json` prints one message per line, with its position; a trace message carries the
                # position of the tactic or term that produced it
                try:
                    j = json.loads(l)
                    ln = j['pos']['line']
                    l = j.get('data', '')
                except (ValueError, KeyError, TypeError):
                    continue
                if not any(a <= ln <= b for a, b in ranges):
                    continue
                for t in pat.findall(l):
                    last = t.split('.')[-1]
                    if any(name_matches(t, u) for u in kept_last.get(last, [])):
                        continue
                    for n in idx.get(last, []):
                        if n in eligible and name_matches(t, C.by[n]['userName']) and n not in hits:
                            hits[n] = {'file': rel, 'line': ln, 'origLine': ln,
                                       'msg': 'used by `%s` in the original elaboration (Lean trace %s)' % (t, opt.split('.', 1)[1])}
        finally:
            pr.wait()
        stages.append({'trace': opt, 'messages': nlines, 'exit': pr.returncode})
        if hits or pr.returncode != 0:
            break
    with open(cache, 'w') as f:
        json.dump({'module': m, 'ranges': ranges, 'stages': stages, 'seconds': round(time.time() - t0, 1),
                   'exit': max(x['exit'] for x in stages), 'hits': sorted(hits), 'detail': hits}, f)
    return hits


def bisect(P, C, work, dele, m, logdir, tag, keep_files):
    """Last resort: find, by rebuilding module `m` only, a small set of deleted declarations whose
    restoration makes it build."""
    vis = C.import_closure(m) | {m}
    cands = sorted(n for n in dele if C.by[n]['module'] in vis)
    count = [0]

    def ok(restore):
        count[0] += 1
        d2 = restore_closure(C, dele, restore)
        apply_set(C, work, d2, keep_files)
        r = build(P, work, [m], os.path.join(logdir, '%s_bisect_%03d.log' % (tag, count[0])))
        return r['exit'] == 0

    if not cands or not ok(cands):
        return None, count[0]

    def mini(cs, fixed):
        if len(cs) <= 1:
            return cs
        h = len(cs) // 2
        a, b = cs[:h], cs[h:]
        if ok(fixed + a):
            return mini(a, fixed)
        if ok(fixed + b):
            return mini(b, fixed)
        a2 = mini(a, fixed + b)
        b2 = mini(b, fixed + a2)
        return a2 + b2
    # try the declarations Lean has in an elaboration table first
    tagged = [n for n in cands if C.attr_tags(C.by[n])]
    if tagged and len(tagged) < len(cands) and ok(tagged):
        return mini(tagged, []), count[0]
    return mini(cands, []), count[0]


def build_other(P, work, logbase):
    """Build what the project builds besides the root modules: Lake's default targets, then the targets the
    project file lists under "extraTargets" (libraries that are not default targets, e.g. comparator files)."""
    parts = [('default targets', [])]
    if P.cfg.get('extraTargets'):
        parts.append(('extra targets', list(P.cfg['extraTargets'])))
    out = {'exit': 0, 'seconds': 0.0, 'modulesBuilt': 0, 'sumModuleSeconds': 0.0, 'errors': [], 'failedTargets': [],
           'what': 'default targets' + (' and ' + ', '.join(P.cfg['extraTargets']) if P.cfg.get('extraTargets') else '')}
    for k, (lab, tg) in enumerate(parts):
        r = build(P, work, tg, '%s_%d.log' % (logbase, k))
        out['exit'] = max(out['exit'], r['exit'])
        out['seconds'] = round(out['seconds'] + r['seconds'], 1)
        out['modulesBuilt'] += r['modulesBuilt']
        out['sumModuleSeconds'] = round(out['sumModuleSeconds'] + r['sumModuleSeconds'], 1)
        out['errors'] += r['errors']
        out['failedTargets'] += r['failedTargets']
    return out


def closure_lines(C, K, dele, keep_files=None):
    """Source lines, before and after, of the modules a build of the roots compiles (their import closure)."""
    need = set()
    for m in K['root_mods']:
        need |= C.import_closure(m) | {m}
    texts, deleted, _ = layout(C, dele, keep_files if keep_files is not None else K['keep_files'])
    nl = lambda L: len(L) - (1 if L and L[-1] == '' else 0)
    before = sum(nl(C.src(m)) for m in need)
    after = sum(nl(texts[m].split('\n')) for m in need if texts.get(m) is not None)
    return {'modulesBefore': len(need), 'modulesAfter': sum(1 for m in need if texts.get(m) is not None),
            'linesBefore': before, 'linesAfter': after}



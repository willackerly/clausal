    ctag = collections.Counter(t for n in cleared for t in K['tags'][n])
    A['attributeCarriersOutOfScope'] = {'n': len(cleared), 'byTag': dict(ctag.most_common())}
    alltag = collections.Counter(t for n in U for t in K['tags'].get(n, ()))
    A['attributeCarriersUnreachable'] = dict(alltag.most_common())

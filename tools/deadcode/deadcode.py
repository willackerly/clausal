def plan_set(C, K, which, sample=None, seed=None):
    by, U = C.by, K['U']
    if which == 'dead':
        dele = set(by) - K['keep_full']
    elif which == 'held':
        dele = set(by) - K['keep_named']
    elif which == 'term':
        dele = set(U)
    else:
        raise SystemExit('unknown set ' + which)
    plan = {'set': which, 'population': len(dele)}
    if sample:
        rng = random.Random(seed)
        picks = rng.sample(sorted(dele), min(sample, len(dele)))
        plan['sampled'] = picks
        plan['seed'] = seed
        dele = C.closure(picks, lambda n: [u for u in C.rG[n] if u in dele])
    ok, notsep = deletable(C, dele)
    plan['delete'] = sorted(ok)
    plan['notSeparable'] = notsep
    return plan



    A['class2Reasons'] = [{'class': c, 'reason': t, 'n': v} for (c, t), v in sorted(tagc.items(), key=lambda kv: (kv[0][0], -kv[1], kv[0][1]))]
    # attribute carriers the scope rule cleared

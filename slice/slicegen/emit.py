"""slicegen emit: Lean text for statements, executable checks, the search script and the audit script.

Every proposition is `<glossary lean def> <variables>`; the only other tokens are
∀ → ∃ ∧, the When's model call, and `ok`.
"""
from __future__ import annotations

import itertools
import re

from .core import Bound, BoundStep, split_list, when_returns

HEADER = "-- GENERATED by slicegen from features/ + glossary.yaml. Do not edit; overwritten on every run.\n"


class Env:
    """Names (or concrete terms) for the variables of one scenario.

    `pre`  : each actor before the first When.
    `post` : each returned actor after the last When that returns it (`x'`).
    `stages`: one entry per When, in order: (BoundStep, call text, [(output name, Lean type)]).
              A When's `pre(x)` argument is the actor's CURRENT state: the initial one, or what the
              latest earlier When handed back. With a single When this is the old one-call form.
              Outputs of a When that is not the last are named `outcome_<k>` / `<actor>_<k>`."""

    def __init__(self, b: Bound, params=None, pre=None):
        self.b = b
        self.params = params or {n: n for n, _ in b.params}
        self.pre = pre or {a: b.var(a) for a, _ in b.actors}
        self.outcome = "outcome"
        cur = dict(self.pre)
        rets = [when_returns(w) for w in b.whens]
        self.stages = []
        for k, w in enumerate(b.whens):
            last = k == len(b.whens) - 1
            stage = _Stage(self.params, cur)
            text = " ".join([w.entry.call] + [arg_term(b, w, a, stage) for a in w.entry.args])
            outs = [("outcome" if last else f"outcome_{k + 1}", w.entry.outcome_type)]
            for a in rets[k]:
                final = not any(a in r for r in rets[k + 1:])
                name = b.var(a) + ("'" if final else f"_{k + 1}")
                outs.append((name, actor_type(b, a)))
                cur = {**cur, a: name}
            self.stages.append((w, text, outs))
        self.post = {a: cur[a] for a in b.returned}


class _Stage:
    """The view a When's arguments are rendered in: `pre(x)` is the current state of x."""

    def __init__(self, params, cur):
        self.params, self.pre, self.post, self.outcome = params, cur, {}, "outcome"


def lit(b: Bound, typ: str, text: str) -> str:
    t = lit_term(b.gloss.param_types, typ, text)
    return t if "enum" in b.gloss.param_types[typ] else "(" + t + ")"


def lit_term(pts: dict, typ: str, text: str) -> str:
    """Lean term for a literal: scalar `{0}`, record `{0} {1} ...` (regex groups), list `{items}`."""
    pt = pts[typ]
    if "enum" in pt:
        return pt["enum"][text]
    if "list_of" in pt:
        items = ", ".join(lit_term(pts, pt["list_of"], x) for x in split_list(text))
        return pt["lean_literal"].format(items=items)
    if pt.get("fields"):
        return pt["lean_literal"].format(*re.fullmatch(pt["literal_regex"], text).groups())
    return pt["lean_literal"].format(text)


def slot_term(b: Bound, bs: BoundStep, name: str, env: Env) -> str:
    v = bs.slots[name]
    if v.kind == "param":
        return env.params[v.text]
    if v.kind == "actor":
        raise ValueError(f"{bs.entry.id}: actor slot `{name}` must be wrapped in pre()/post()")
    return lit(b, v.type, v.text)


def arg_term(b: Bound, bs: BoundStep, arg: str, env: Env, notes=None) -> str:
    m = re.fullmatch(r"(pre|post|all_pre|all_post)\((\w+)\)", arg)
    if not m:
        return env.outcome if arg == "outcome" else slot_term(b, bs, arg, env)
    fn, x = m.groups()
    if fn in ("all_pre", "all_post"):
        names = [a for a, t in b.actors if t == x]
        src = env.pre if fn == "all_pre" else {**env.pre, **env.post}
        return "[" + ", ".join(src[a] for a in names) + "]"
    actor = bs.slots[x].text
    if fn == "post":
        if actor in env.post:
            return env.post[actor]
        if notes is not None:
            notes.append(actor)
        return env.pre[actor]
    return env.pre[actor]


def prop(b: Bound, bs: BoundStep, env: Env, notes=None) -> str:
    return " ".join([bs.entry.lean] + [arg_term(b, bs, a, env, notes) for a in bs.entry.args])


def call(b: Bound, env: Env) -> str:
    """The model call of a single-When scenario (or the last call of a chain)."""
    return env.stages[-1][1]


def all_outs(env: Env) -> list:
    """Every output of every When, in order: [(name, Lean type)]."""
    return [o for _, _, outs in env.stages for o in outs]


def tuple_of(outs) -> str:
    return "(" + ", ".join(n for n, _ in outs) + ")"


def chain(b: Bound, env: Env) -> str:
    """One `Result` term running every When in order and returning all their outputs as one flat tuple.
    For a single When this is just the call."""
    if not b.multi:
        return env.stages[0][1]
    lines = [f"let {tuple_of(outs) if len(outs) > 1 else outs[0][0]} ← {text}" for _, text, outs in env.stages]
    return "(do " + "; ".join(lines) + f"; ok {tuple_of(all_outs(env))})"


def actor_type(b: Bound, a: str) -> str:
    return b.gloss.actors[dict(b.actors)[a]]["lean"]


def group(pairs) -> str:
    """[(name, type)] -> `(a b : T) (c : U)`."""
    out = []
    for typ, grp in itertools.groupby(pairs, key=lambda p: p[1]):
        out.append("(" + " ".join(n for n, _ in grp) + " : " + typ + ")")
    return " ".join(out)


def in_binders(b: Bound) -> list:
    return ([(n, b.gloss.param_types[t]["lean"]) for n, t in b.params]
            + [(b.var(a), actor_type(b, a)) for a, _ in b.actors])


def out_binders(b: Bound) -> list:
    """Every output of every When (for a single When: `outcome` and the returned actors)."""
    return all_outs(Env(b))


def out_tuple(b: Bound) -> str:
    return tuple_of(out_binders(b))


def frame_trivial(b: Bound) -> list:
    """Then steps that mention post(x) of an actor the call does not return."""
    out = []
    for t in b.thens:
        notes = []
        prop(b, t, Env(b), notes)
        if notes:
            out.append((t, notes))
    return out


def statement(b: Bound, env: Env | None = None, name: str | None = None) -> str:
    env = env or Env(b)
    lines = [f"def {name or b.id + '.stmt'} : Prop :=", f"  ∀ {group(in_binders(b))},"]
    lines += [f"    {prop(b, g, env)} →" for g in b.givens]
    # one `∃ outputs, call = ok outputs ∧` per When, nested in order; the Thens come last
    for _, text, outs in env.stages[:-1]:
        lines.append(f"    ∃ {group(outs)},")
        lines.append(f"      {text} = ok {tuple_of(outs)} ∧")
    _, text, outs = env.stages[-1]
    lines.append(f"    ∃ {group(outs)},")
    body = [f"{text} = ok {tuple_of(outs)}"] + [prop(b, t, env) for t in b.thens]
    lines += [f"      {p} ∧" for p in body[:-1]] + [f"      {body[-1]}"]
    return "\n".join(lines)


def statements_file(bounds) -> str:
    g = bounds[0].gloss if bounds else None
    imports = "".join(f"import {i}\n" for i in (g.raw["lean_imports"] if g else []))
    out = [HEADER + imports + "open Aeneas Aeneas.Std Result\n"]
    for b in bounds:
        sc = b.sc
        doc = f"/-- {sc.feature.path}:{sc.line}  ({b.scope})\n" + "\n".join("    " + l for l in sc.text.splitlines()) + " -/"
        out.append(doc + "\n" + statement(b) + "\n")
    return "\n".join(out)


# --------------------------------------------------------------------------- executable checks

def checks_file(bounds) -> str:
    out = [HEADER + "import Wallet.Statements\nopen Aeneas Aeneas.Std Result\nset_option linter.unusedVariables false\n"]
    for b in bounds:
        env = Env(b)
        bind = group(in_binders(b))
        args = " ".join(n for n, _ in in_binders(b))
        gs = ", ".join(f"decide ({prop(b, g, env)})" for g in b.givens)
        ts = ", ".join(f"decide ({prop(b, t, env)})" for t in b.thens)
        conj = " ∧ ".join(prop(b, t, env) for t in b.thens)
        tup = tuple_of(all_outs(env))
        run = chain(b, env)
        shows = [f"{{{b.when.entry.outcome_show} outcome}}"] + [
            f"{a}: {{{b.gloss.actors[dict(b.actors)[a]]['show']} {env.post[a]}}}" for a in b.returned]
        out.append(
            f"def {b.id}.givens {bind} : List Bool :=\n  [{gs}]\n"
            f"def {b.id}.thens {bind} : Option (List Bool) :=\n"
            f"  Bdd.runThens ({run}) (fun {tup} => [{ts}])\n"
            f"def {b.id}.returned {bind} : String :=\n"
            f"  Bdd.showResult ({run}) (fun {tup} => s!\"{'; '.join(shows)}\")\n"
            f"def {b.id}.check {bind} : Bdd.Check :=\n"
            f"  if ({b.id}.givens {args}).all id then\n"
            f"    Bdd.run ({run}) (fun {tup} => decide ({conj}))\n"
            f"  else .givenFalse\n")
    return "\n".join(out)


# --------------------------------------------------------------------------- concrete instantiation

def build_term(b: Bound, a: str, params: dict) -> str:
    """Concrete Lean term building actor `a`, given concrete terms for parameters (incl. hidden ones)."""
    how, x = b.builders[a]
    if how == "hidden":
        return "(" + b.gloss.actors[dict(b.actors)[a]]["build"]["with"].format(params[x]) + ")"
    g = x
    env = Env(b, params=params)
    fill = {name: slot_term(b, g, name, env) for typ, name in g.entry.slots if g.slots[name].kind != "actor"}
    return "(" + g.entry.builds["with"].format(**fill) + ")"


def concrete_env(b: Bound, values: dict) -> Env:
    """values: param/hidden name -> literal text (digits or enum key)."""
    types = dict(b.params + b.hidden)
    params = {n: lit(b, types[n], v) for n, v in values.items()}
    pre = {a: build_term(b, a, params) for a, _ in b.actors}
    return Env(b, params={n: params[n] for n, _ in b.params}, pre=pre)


def concrete_args(b: Bound, values: dict) -> str:
    env = concrete_env(b, values)
    return " ".join([env.params[n] for n, _ in b.params] + [env.pre[a] for a, _ in b.actors])


def grid_values(b: Bound, typ: str) -> list:
    pt = b.gloss.param_types[typ]
    if "enum" in pt:
        return list(pt["enum"])
    vals = [str(v) for v in pt.get("sample", [])]
    mx = pt.get("max")
    scalar = "list_of" not in pt and not pt.get("fields")
    for bs in b.all_steps:      # literals in the scenario (and, for numbers, their neighbours)
        for v in bs.slots.values():
            if v.kind == "lit" and v.type == typ:
                if not scalar:
                    if v.text not in vals:
                        vals.append(v.text)
                    continue
                for n in (int(v.text), int(v.text) - 1, int(v.text) + 1):
                    if n >= 0 and (mx is None or n <= mx) and str(n) not in vals:
                        vals.append(str(n))
    return vals


def search_vars(b: Bound) -> list:
    return b.params + b.hidden


def search_file(bounds) -> str:
    out = [HEADER + "-- Run once per pipeline run with `lake env lean Run/Search.lean` (interpreter).\n"
           "-- Evaluates every Examples row on the Lean model and searches a boundary grid for\n"
           "-- (a) an input satisfying the Givens and (b) an input where the scenario fails.\n"
           "import Wallet.Checks\nopen Aeneas Aeneas.Std Result\n"]
    main = []
    for k, b in enumerate(bounds):
        # rows
        if not b.hidden:
            for n, (line, cells) in enumerate(b.sc.rows if b.sc.outline else [(b.sc.line, [])], 1):
                args = concrete_args(b, dict(zip(b.sc.header, cells)))
                main.append(f'  IO.println (Bdd.rowLine "{b.id}" {n} ({b.id}.check {args}) ({b.id}.givens {args}) '
                            f'({b.id}.thens {args}) ({b.id}.returned {args}))')
        # grid
        vars_ = search_vars(b)
        fn = [f"def search{k} : IO Unit := do",
              "  let mut tried := 0", "  let mut sat : Option String := none", "  let mut bad : Option String := none"]
        ind = "  "
        for i, (n, t) in enumerate(vars_):
            vals = ", ".join(lit(b, t, v) for v in grid_values(b, t))
            fn.append(f"{ind}for ({n}, i{i}) in ([{vals}] : List ({b.gloss.param_types[t]['lean']})).zipIdx do")
            ind += "  "
        pvars = {n: n for n, _ in vars_}
        for a, _ in b.actors:
            fn.append(f"{ind}let {b.var(a)} := {build_term(b, a, pvars)}")
        args = " ".join(n for n, _ in in_binders(b))
        idx = "[" + ", ".join(f"i{i}" for i in range(len(vars_))) + "]" if vars_ else "([] : List Nat)"
        fn += [f"{ind}tried := tried + 1",
               f"{ind}let c := {b.id}.check {args}",
               f"{ind}if c != .givenFalse then",
               f"{ind}  if sat.isNone then sat := some (toString {idx})",
               f"{ind}  if c != .pass && bad.isNone then",
               f"{ind}    bad := some (Bdd.badLine {idx} c ({b.id}.thens {args}) ({b.id}.returned {args}))",
               f'  IO.println (Bdd.searchLine "{b.id}" tried sat bad)']
        out.append("\n".join(fn) + "\n")
        main.append(f"  search{k}")
    if bounds:
        pdefs, pmain = phrase_grid_lean(bounds[0].gloss)
        out.append("-- The two readings of each phrase: every glossary definition evaluated on a grid of arguments.\n"
                   "-- The Rust predicates (wallet-bdd/src/lib.rs) are evaluated on the same grid; the report compares.")
        out += pdefs
        main += pmain
    out.append("#eval show IO Unit from do\n" + ("\n".join(main) if main else "  pure ()") + "\n")
    return "\n".join(out)


# --------------------------------------------------------------------------- derived theorems + audit

def vocab_defs(b: Bound) -> list:
    seen = []
    for bs in b.givens + b.thens:
        if bs.entry.lean not in seen:
            seen.append(bs.entry.lean)
    return seen


def hint_simp(b: Bound) -> list:
    """Extra simp lemmas for the generated scripts (glossary `proof_hints.simp`): facts about the
    constructors used to build concrete values. They never change what a theorem says."""
    return list(b.gloss.raw.get("proof_hints", {}).get("simp", []))


def builder_defs(b: Bound) -> list:
    """Definitions used to build concrete actors (e.g. Vocab.mkWallet)."""
    seen = []
    templates = [b.gloss.actors[t]["build"]["with"] for _, t in b.actors]
    templates += [g.entry.builds["with"] for g in b.givens if g.entry.builds]
    keep_folded = b.gloss.raw.get("proof_hints", {}).get("keep_folded", [])
    for t in templates:
        n = t.split()[0]
        if n not in seen and n not in keep_folded:     # a folded builder is handled by a `proof_hints.simp` lemma
            seen.append(n)
    return seen


def close_tac(simp_set: str) -> str:
    return (f"first | trivial | decide | (simp [{simp_set}]; done) | (simp [{simp_set}]; scalar_tac) | scalar_tac")


def sat_theorem(b: Bound, values: dict) -> str:
    env = Env(b)
    conj = " ∧ ".join(prop(b, g, env) for g in b.givens) or "True"
    cenv = concrete_env(b, values)
    wit = ", ".join([cenv.params[n] for n, _ in b.params] + [cenv.pre[a] for a, _ in b.actors])
    simp = ", ".join(vocab_defs(b) + builder_defs(b) + hint_simp(b))
    return (f"/-- The Givens can all hold at once (so a proof of the statement is not vacuous). -/\n"
            f"theorem {b.id}.sat : ∃ {group(in_binders(b))}, {conj} :=\n"
            f"  ⟨{wit}, by {close_tac(simp)}⟩\n")


def unsat_theorem(b: Bound) -> str:
    env = Env(b)
    conj = " ∧ ".join(prop(b, g, env) for g in b.givens)
    names = ", ".join(n for n, _ in in_binders(b))
    simp = ", ".join(vocab_defs(b))
    return (f"/-- No input satisfies all the Givens: the scenario is true of nothing. -/\n"
            f"theorem {b.id}.unsat : ¬ ∃ {group(in_binders(b))}, {conj} := by\n"
            f"  rintro ⟨{names}, h⟩\n"
            f"  first | (simp [{simp}] at h; done) | (simp [{simp}] at h; scalar_tac) | scalar_tac\n")


def refuted_theorem(b: Bound, values: dict) -> str | None:
    """Kernel-checkable refutation at a concrete witness (recipe of DESIGN.md worked example C).
    Not generated for a multi-When scenario (the statement nests one ∃ per When; see DESIGN.md 12)."""
    if b.multi:
        return None
    cenv = concrete_env(b, values)
    simp = ", ".join(vocab_defs(b) + builder_defs(b) + hint_simp(b))
    outs = out_binders(b)
    n = len(outs)
    given_proofs = " ".join(f"(by {close_tac(simp)})" for _ in b.givens)
    conj = " ∧ ".join(prop(b, t, cenv) for t in b.thens)
    names = ", ".join(x for x, _ in outs)
    names2 = ", ".join(f"x{i}" for i in range(n))
    rfls = ", ".join("rfl" for _ in range(n))
    extra = "".join(", " + x for x in b.gloss.raw.get("proof_hints", {}).get("refute_simp", []))
    more = "".join(", " + x for x in b.gloss.raw.get("proof_hints", {}).get("refute_simp_more", []))
    closers = (f"       all_goals first\n"
               f"         | (simp [{simp}] at *; done)\n"
               f"         | (simp [{simp}] at *; scalar_tac)\n"
               f"         | (simp_all [{simp}]; done)\n"
               f"         | (simp_all [{simp}]; scalar_tac)\n"
               f"         | (simp_all [{simp}{extra}]; done)\n"
               f"         | (simp_all [{simp}{extra}]; scalar_tac)\n"
               f"         | (simp_all [{simp}{extra}{more}]; done)\n"
               f"         | (simp_all [{simp}{extra}{more}]; scalar_tac))\n")
    split = (f"  simp only [Prod.mk.injEq] at e3\n  obtain ⟨{rfls}⟩ := e3\n" if n > 1 else "  subst e3\n")
    return (f"/-- The statement is FALSE: at this input the model returns a value that fails a Then. -/\n"
            f"theorem {b.id}.refuted : ¬ {b.id}.stmt := by\n"
            f"  intro h\n"
            f"  obtain ⟨{names}, e, t⟩ := h {concrete_args(b, values)} {given_proofs}\n"
            f"  have w : ∃ {group(outs)}, {call(b, cenv)} = ok {out_tuple(b)} ∧\n"
            f"      ¬ ({conj}) := by\n"
            f"    apply Bdd.ok{n}_of_spec\n"
            f"    first\n"
            f"    | (unfold {b.when.entry.call}\n"
            f"       step*\n"
            f"{closers}"
            f"    -- a loop cannot be stepped through; this works only if a hand-proved `@[step]` lemma about the\n"
            f"    -- call is imported (glossary `audit_imports`) and says enough at this input\n"
            f"    | (step*\n"
            f"{closers}"
            f"  obtain ⟨{names2}, e2, t2⟩ := w\n"
            f"  rw [e] at e2\n"
            f"  have e3 := Bdd.ok_inj e2\n"
            f"{split}"
            f"  exact t2 t\n")


def trivial_theorems(b: Bound) -> str:
    """One attempt per Then: does it follow from the Givens alone, with outcome and post-states arbitrary?
    These are EXPECTED to fail for a meaningful Then; success raises the TRIVIAL-THEN flag."""
    env = Env(b)
    simp = ", ".join(vocab_defs(b))
    out = []
    for k, t in enumerate(b.thens, 1):
        hyps = "".join(f"{prop(b, g, env)} → " for g in b.givens)
        out.append(f"theorem {b.id}.trivial_{k} : ∀ {group(in_binders(b) + out_binders(b))}, {hyps}{prop(b, t, env)} := by\n"
                   f"  intros\n"
                   f"  first | (simp_all [{simp}]; done) | (simp_all [{simp}]; scalar_tac) | scalar_tac\n")
    return "\n".join(out)


def lean_names(names) -> str:
    return "#[" + ", ".join("`" + n for n in names) + "]"


def lean_pairs(pairs) -> str:
    return "#[" + ", ".join(f"(`{a}, `{b})" for a, b in pairs) + "]"


# --------------------------------------------------------------------------- input coverage

def coverage_groups(bounds) -> list:
    """Universal scenarios that are meant to be proved, grouped by (When entry, variables).

    For each group, a statement that the scenarios' Givens, taken together, leave no input out:

        ∀ <the When's own inputs: every actor, and the parameters the When step mentions>,
          ∃ <the other parameters>, <the constructive Givens shared by all> ∧ (<rest of scenario 1> ∨ <rest of scenario 2> ∨ ...)

    A constructive Given (one with `builds`, e.g. "Alice has a balance of <a>") only names a value, which is
    why its parameter is existential: the theorem has to exhibit it, nothing is assumed.
    Returns [{name, call, when, ids, text}].
    """
    groups = {}
    for b in bounds:
        if b.scope != "universal" or b.sc.expect or b.hidden or b.multi:
            continue           # a multi-When scenario constrains a sequence, not one operation's inputs
        key = (b.when.entry.id, tuple(in_binders(b)))
        groups.setdefault(key, []).append(b)
    out = []
    for k, ((wid, binders), bs) in enumerate(groups.items()):
        b0 = bs[0]
        when_params = {v.text for v in b0.when.slots.values() if v.kind == "param"}
        ptype = {n: b0.gloss.param_types[t]["lean"] for n, t in b0.params}
        univ = [(n, t) for n, t in binders if n not in ptype or n in when_params]
        aux = [(n, t) for n, t in binders if n in ptype and n not in when_params]
        props = [[(prop(b, g, Env(b)), bool(g.entry.builds)) for g in b.givens] for b in bs]
        shared = [p for p, builds in props[0] if builds and all((p, True) in q for q in props[1:])]
        rests = [[p for p, _ in q if p not in shared] for q in props]
        disj = " ∨\n      ".join("(" + (" ∧ ".join(r) or "True") + ")" for r in rests)
        simp = []
        for b in bs:
            for d in vocab_defs(b):
                if d not in simp:
                    simp.append(d)
        simp = ", ".join(simp)
        name = f"Coverage.g{k}"
        body = " ∧\n    ".join(shared + [f"({disj})"])
        ex = f"∃ {group(aux)}, " if aux else ""
        wit = ", ".join(["_"] * len(aux) + ["rfl"] * len(shared) + ["?_"])
        text = (f"/-- No input to `{b0.when.entry.call}` falls outside the Givens of all of:\n"
                + "".join(f"    {b.id}\n" for b in bs) + "-/\n"
                f"theorem {name} : ∀ {group(univ)}, {ex}\n    {body} := by\n"
                f"  intros\n"
                f"  refine ⟨{wit}⟩\n"
                f"  first | (simp_all [{simp}]; done) | (simp_all [{simp}]; scalar_tac) | scalar_tac"
                f" | exact Classical.em _ | exact (Classical.em _).symm\n")
        out.append({"name": name, "call": b0.when.entry.call, "when": wid, "ids": [b.id for b in bs], "text": text})
    return out


def audit_file(bounds, search: dict, model_fns: list, proof_modules: dict, extra=()) -> str:
    """proof_modules: scenario id -> Lean module holding its hand-written proof, for the modules that compiled.
    extra: hand-written lemma libraries (glossary `audit_imports`) that compiled."""
    out = [HEADER + "-- Run once per pipeline run with `lake env lean Run/Audit.lean`.\n"
           "-- Part 1: theorems DERIVED from the search results (satisfiability, vacuity, refutation,\n"
           "--         trivial-Then attempts, input coverage). A theorem whose script fails is logged as\n"
           "--         an error and shows up below with `sorryAx`, which the report counts as no theorem.\n"
           "-- Part 2: the audit proper, printed as one JSON line.\n"
           "-- Only the hand-written proof modules that compiled are imported.\n"
           + "".join(f"import {m}\n" for m in proof_modules.values())
           + "".join(f"import {m}\n" for m in extra)
           + "import Wallet.Checks\nimport Bdd.Audit\nopen Aeneas Aeneas.Std Result\n"
           "set_option linter.unusedTactic false\nset_option linter.unreachableTactic false\n"
           "set_option linter.unusedSimpArgs false\nset_option linter.unusedVariables false\n"]
    proofs, refutations, derived, stmts, defs = [], [], [], [], []
    for b in bounds:
        s = search.get(b.id, {})
        proofs.append((b.id, b.id + ".stmt"))
        stmts.append(b.id + ".stmt")
        for d in vocab_defs(b):
            if d not in defs:
                defs.append(d)
        out.append(f"-- ===== {b.id}")
        if s.get("sat") is not None:
            out.append(sat_theorem(b, s["sat"]))
            derived.append(b.id + ".sat")
        else:
            out.append(unsat_theorem(b))
            derived.append(b.id + ".unsat")
        if s.get("bad") is not None and refuted_theorem(b, s["bad"]["values"]):
            out.append(refuted_theorem(b, s["bad"]["values"]))
            refutations.append((b.id + ".refuted", b.id + ".stmt"))
        out.append(trivial_theorems(b))
        derived += [f"{b.id}.trivial_{k}" for k in range(1, len(b.thens) + 1)]
    out.append("-- ===== input coverage: do the proved scenarios of one operation cover every input?")
    for g in coverage_groups(bounds):
        out.append(g["text"])
        derived.append(g["name"])
    for e in (bounds[0].gloss.entries if bounds else []):     # every glossary definition, used or not
        if e.kind != "when" and e.lean not in defs:
            defs.append(e.lean)
    out.append(f"#eval Bdd.Audit.report\n  (proofs := {lean_pairs(proofs)})\n  (refutations := {lean_pairs(refutations)})\n"
               f"  (derived := {lean_names(derived)})\n  (stmts := {lean_names(stmts)})\n"
               f"  (defs := {lean_names(defs)})\n  (fns := {lean_names(model_fns)})\n")
    return "\n".join(out)


# --------------------------------------------------------------------------- the two readings of a phrase

def phrase_grid(gloss) -> list:
    """For every Given/Then glossary entry: a grid of concrete arguments on which the Lean definition
    (lean/Wallet/Vocab.lean) and the Rust predicate (wallet-bdd/src/lib.rs) are both evaluated.

    Returns [{id, vars: [(lean type, [lean literal], [plain token])], term: Lean proposition over x0.., args: [[var index]]}].
    Each glossary arg becomes one variable, or two for `all_pre(T)` / `all_post(T)` (a list of two actors).
    """
    pts, actors = gloss.param_types, gloss.actors

    def domain(typ):
        pt = pts[typ]
        if "enum" in pt:
            return pt["lean"], list(pt["enum"].values()), list(pt["enum"])
        vals = [str(v) for v in pt.get("sample", [])]
        return pt["lean"], ["(" + lit_term(pts, typ, v) + ")" for v in vals], vals

    out = []
    for e in gloss.entries:
        if e.kind == "when":
            continue
        slots = {name: typ for typ, name in e.slots}
        vars_, terms, args = [], [], []

        def actor_var(atype):
            b = actors[atype]["build"]
            vars_.append(domain(b["param_type"]))
            return "(" + b["with"].format(f"x{len(vars_) - 1}") + ")"

        for a in e.args:
            m = re.fullmatch(r"(pre|post|all_pre|all_post)\((\w+)\)", a)
            first = len(vars_)
            if a == "outcome":
                ov = gloss.raw["outcome_values"][e.outcome_type]      # a Then about `outcome` names its result type
                vars_.append((e.outcome_type, list(ov.values()), list(ov)))
                terms.append(f"x{first}")
            elif m and m.group(1) in ("pre", "post"):
                terms.append(actor_var(slots[m.group(2)]))
            elif m:
                terms.append("[" + ", ".join(actor_var(m.group(2)) for _ in range(2)) + "]")
            else:
                vars_.append(domain(slots[a]))
                terms.append(f"x{first}")
            args.append(list(range(first, len(vars_))))
        out.append({"id": e.id, "lean": e.lean, "vars": vars_, "term": " ".join([e.lean] + terms), "args": args})
    return out


def phrase_grid_lean(gloss) -> tuple:
    """(definitions, main lines) evaluating every glossary definition on its grid; one PHRASE line each."""
    defs, main = [], []
    for k, g in enumerate(phrase_grid(gloss)):
        fn = [f"def phrase{k} : String := Id.run do", "  let mut s := \"\""]
        ind = "  "
        for i, (typ, lits, _) in enumerate(g["vars"]):
            fn.append(f"{ind}for x{i} in ([{', '.join(lits)}] : List ({typ})) do")
            ind += "  "
        fn += [f"{ind}s := s.push (if decide ({g['term']}) then '1' else '0')", "  return s"]
        defs.append("\n".join(fn) + "\n")
        main.append(f'  IO.println s!"PHRASE\\t{g["id"]}\\t{{phrase{k}}}"')
    return defs, main


def phrase_grid_rows(gloss) -> dict:
    """glossary id -> the grid rows, each a list of plain-text args (an all_pre/all_post list is one comma-separated arg),
    in the order in which the Lean side evaluates them."""
    out = {}
    for g in phrase_grid(gloss):
        out[g["id"]] = [[",".join(combo[i] for i in idx) for idx in g["args"]]
                        for combo in itertools.product(*[toks for _, _, toks in g["vars"]])]
    return out


def phrase_grid_tsv(gloss) -> str:
    """The grid as plain rows for the Rust side: id <TAB> arg <TAB> arg ..."""
    return "".join("\t".join([i] + row) + "\n" for i, rows in phrase_grid_rows(gloss).items() for row in rows)


# --------------------------------------------------------------------------- counterexample replay on Rust

def replay_feature(bounds, search: dict) -> str:
    """A feature file holding each found counterexample as a literal scenario, for cucumber-rs.
    Expected result on the compiled Rust: the Givens hold and a Then fails."""
    out = ["Feature: Counterexample replay",
           "  GENERATED by slicegen from the counterexamples found on the Lean model. Each scenario is",
           "  expected to FAIL on the compiled Rust in the same way.", ""]
    for b in bounds:
        bad = search.get(b.id, {}).get("bad")
        if not bad or b.hidden:
            continue
        out.append(f"  Scenario: {b.id}")
        for bs in b.all_steps:
            t = bs.step.text
            for n, v in bad["values"].items():
                t = t.replace(f"<{n}>", v)
            out.append(f"    {bs.step.keyword} {t}")
        out.append("")
    return "\n".join(out) if len(out) > 4 else ""

"""clausal evgen: GENERATED property tests and bounded-model-checking harnesses (plan node E1).

From the SAME composition tree that gives a sentence its Lean statement and its echo (build/trees.json, written by
`clausal gen`), this module writes Rust. Nothing below is written per rule:

  evidence/src/checks.rs         per compiled reading (scenario or Rule line) ONE function `check_<n>`: the reading at one
                                 point, as straight-line typed Rust over the typed per-piece readings of
                                 evidence/src/typed.rs. It returns the same bits the grid comparison prints (per unit its
                                 scope, per claim the relation between two calls and the claim) and whether every claim holds.
  evidence/src/table.rs          per reading: its variables with their types, which of them a Given FIXES (an actor that
                                 "holds the balances <balances>" is not generated: it is that value), which belong to the
                                 second call of a two-run rule, the numbers written in the sentence, and a glue function
                                 from generated values to `check_<n>`. The generic runner (evidence/src/main.rs) derives
                                 edge-weighted generators from exactly this and runs proptest with shrinking.
  evidence/kani/src/harnesses.rs per reading and per rung of the size ladder ONE `#[kani::proof]`: every integer fully
                                 symbolic, collections up to the rung's sizes, `assert!(check_<n>(...).holds)`.

The ladder (LADDER below) is the same for every rule and every mutant. A reading with no collection has one harness and
no size bound.

Like the rest of clausal this is untrusted: the property test compares `check_<n>` with the tree evaluator of
wallet-bdd/src/pieces.rs at every generated case, and that evaluator is compared with the Lean definitions on the grid.
"""
from __future__ import annotations

import json
import re

# (accounts, transfers per batch): the size ladder of the bounded check, the same for every rule and every mutant.
# From compare/TRADES.md section 4: a third and fourth account is what a total rule needs to show some bugs, a third
# transfer what others need, and rules without a total verify quickly at 6 and 4. The first rung is the smallest size at
# which a two-step rule (two batches, a batch against a reference) gets an answer at all.
LADDER = [(2, 1), (2, 2), (4, 1), (2, 3), (6, 4)]

HEAD = "// GENERATED by `python3 -m clausal gen` (clausal/evgen.py) from build/trees.json. Do not edit.\n"


class Unsupported(Exception):
    pass


def san(name: str) -> str:
    return re.sub(r"\W", "_", name)


def items(text: str) -> list:
    inner = text.strip()
    assert inner.startswith("[") and inner.endswith("]"), text
    inner = inner[1:-1].strip()
    return inner.split(", ") if inner else []


def tr_lit(text: str) -> tuple:
    f, rest = text.strip().split("->")
    t, a = rest.split(":")
    return int(f), int(t), int(a)


def lit_expr(typ: str, text: str) -> tuple:
    """(Rust expression, sort) of a literal of a Clausebook literal type."""
    if typ in ("amount", "index"):
        return f"{int(text)}u128", "num"
    if typ == "balances":
        xs = items(text)
        return ("(&[" + ", ".join(f"{int(x)}u64" for x in xs) + "][..])") if xs else "(&[0u64; 0][..])", "list"
    if typ == "transfer":
        f, t, a = tr_lit(text)
        return f"({f}usize, {t}usize, {a}u64)", "transfer"
    if typ == "batch":
        xs = [tr_lit(x) for x in items(text)]
        return ("(&[" + ", ".join(f"({f}usize, {t}usize, {a}u64)" for f, t, a in xs) + "][..])") if xs else "(&[(0usize, 0usize, 0u64); 0][..])", "list"
    if typ == "error":
        return {"insufficient funds": "WAns::InsufficientFunds", "overflow": "WAns::Overflow", "ok": "WAns::Ok"}[text], "name"
    raise Unsupported(f"literal type {typ}")


def numbers_in(x, out: set):
    """Every number written in a tree (the literals of the sentence): they join the generators' pool of edge values."""
    if isinstance(x, list):
        for y in x:
            numbers_in(y, out)
    elif isinstance(x, dict):
        if "lit" in x and x["lit"] is not None:
            out.update(int(n) for n in re.findall(r"\d+", x["lit"]))
        for v in (x.get("a") or {}).values():
            numbers_in(v, out)


def lits_in(x, out: list):
    """Every literal written in a tree."""
    if isinstance(x, list):
        for y in x:
            lits_in(y, out)
    elif isinstance(x, dict):
        if x.get("lit") is not None:
            out.append(x["lit"])
        for k in ("a", "node", "conds", "claims"):
            if k in x:
                lits_in(x[k] if not isinstance(x[k], dict) or k != "a" else list(x[k].values()), out)


ANS_SORT = {"w.transfer": "name", "w.deposit": "name", "w.withdraw": "name", "l.apply_batch": "num", "l.apply_all": "bool",
            "l.apply": "bool", "l.total": "opt", "l.lookup": "opt"}
ACCEPTED = {"w.transfer": "({a} == WAns::Ok)", "w.deposit": "({a} == WAns::Ok)", "w.withdraw": "({a} == WAns::Ok)",
            "l.apply_batch": "true", "l.apply_all": "{a}", "l.apply": "{a}", "l.total": "{a}.is_some()", "l.lookup": "{a}.is_some()"}
RUN_FN = {"w.transfer": "w_transfer", "w.deposit": "w_deposit", "w.withdraw": "w_withdraw", "l.apply_batch": "l_apply_batch",
          "l.apply_all": "l_apply_all", "l.apply": "l_apply", "l.total": "l_total", "l.lookup": "l_lookup"}
RUST_TY = {"amount": "u64", "index": "u64", "balances": "&[u64]", "transfer": "T", "batch": "&[T]"}
CALLS = {"rejected": "Calls::Rejected", "successful": "Calls::Accepted"}


def calls_of(mods) -> str:
    return CALLS["rejected"] if "rejected" in mods else CALLS["successful"] if "successful" in mods else "Calls::Every"


class Env:
    """What a piece is read on: the variables a leaf may name, the actors with the state they are read in, the answer,
    the item a quantifier is at."""

    def __init__(self, refs, actors, ans=None, op=None, item=None, depth=0):
        self.refs, self.actors, self.ans, self.op, self.item, self.depth = refs, actors, ans, op, item, depth

    def with_item(self, expr, sort):
        return Env(self.refs, self.actors, self.ans, self.op, (expr, sort), self.depth + 1)

    def with_actors(self, actors):
        return Env(self.refs, actors, self.ans, self.op, self.item, self.depth)


def eq(a, b) -> str:
    (ea, sa), (eb, sb) = a, b
    if sa != sb:
        raise Unsupported(f"comparing a {sa} with a {sb}")
    return f"same({ea}, {eb})" if sa == "list" else f"({ea} == {eb})"


def gen(x, e: Env) -> tuple:
    """(Rust expression, sort) of a tree: ONE arm per domain word and per modifier, calling evidence/src/typed.rs."""
    if isinstance(x, list):
        parts = [gen(y, e) for y in x]
        if any(s != "num" for _, s in parts):
            raise Unsupported("a list that is not of numbers")
        return "[" + ", ".join(p for p, _ in parts) + "]", "list"
    if "k" in x:
        if x["k"] == "actor":
            if x["ref"] not in e.actors:
                raise Unsupported(f"actor {x['ref']} is not in this state")
            return e.actors[x["ref"]], x["type"]
        if x.get("lit") is not None:
            return lit_expr(x["type"], x["lit"])
        if x["ref"] not in e.refs:
            raise Unsupported(f"nothing binds {x['ref']}")
        v, typ = e.refs[x["ref"]]
        if typ != x["type"]:
            raise Unsupported(f"{x['ref']} is a {typ}, wanted a {x['type']}")
        return (f"({v} as u128)", "num") if typ in ("amount", "index") else (v, "list" if typ in ("balances", "batch") else typ)
    p = x["p"]
    A = x.get("a") or {}

    def a(name, env=e):
        return gen(A[name], env)

    def n(name):
        ex, s = a(name)
        if s != "num":
            raise Unsupported(f"{p}: {name} is a {s}, not a number")
        return ex

    def ans(sort=None):
        if e.ans is None:
            raise Unsupported(f"{p} speaks of the answer, and there is none here")
        if sort and ANS_SORT[e.op] != sort:
            raise Unsupported(f"{p}: the answer of {e.op} is a {ANS_SORT[e.op]}")
        return e.ans

    if x.get("per_actor"):
        if p != "w.balance":
            raise Unsupported(f"no plural reading of {p}")
        return "[" + ", ".join(f"({ex} as u128)" for ex in e.actors.values()) + "]", "list"
    if p == "w.balance":
        return f"({a('w')[0]} as u128)", "num"
    if p in ("w.maximum", "l.maximum"):
        return "MAX", "num"
    if p == "w.succeeds":
        return f"({ans('name')} == WAns::Ok)", "bool"
    if p == "w.rejected_with":
        return f"({ans('name')} == {a('e')[0]})", "bool"
    if p in ("l.ledger", "l.balances_of"):
        return a("l")[0], "list"
    if p == "l.bal_of":
        return f"bal_of({a('l')[0]}, {n('k')})", "num"
    if p == "l.balance_at":
        return f"balance_at({a('l')[0]}, {n('i')})", "opt"
    if p == "l.accounts":
        return f"Accounts({a('l')[0]}.len())", "list"
    if p == "l.is_account":
        return f"({n('i')} < {a('l')[0]}.len() as u128)", "bool"
    if p == "l.valid":
        if e.item is None or e.item[1] != "transfer":
            raise Unsupported("`valid on` is said of a transfer")
        return f"valid({a('l')[0]}, {e.item[0]})", "bool"
    if p == "l.the_transfer":
        return a("t")
    if p == "l.transfers":
        return a("b")
    if p == "l.length":
        return f"({a('b')[0]}.len() as u128)", "num"
    if p in ("l.sender", "l.receiver", "l.amount_of"):
        return f"({a('t')[0]}.{('l.sender', 'l.receiver', 'l.amount_of').index(p)} as u128)", "num"
    if p == "l.applied":
        return ans("num"), "num"
    if p == "l.stopped_at":
        return f"stopped_at({a('b')[0]}, {ans('num')})", "list"
    if p == "l.result":
        return ans(), ANS_SORT[e.op]
    if p == "l.accepted":
        return f"({ans('bool')} == true)", "bool"
    if p == "l.found":
        return f"{ans('opt')}.is_some()", "bool"
    if p in ("amount_value", "index_number", "index_count", "balances_value"):
        return a("x")
    if p == "amount_result":
        return f"Some({n('x')})", "opt"
    if p == "zero":
        return "0u128", "num"
    if p == "is":
        return eq(a("m"), a("t")), "bool"
    if p == "equals":
        return eq(a("a"), a("b")), "bool"
    if p == "not_more_than":
        return f"({n('t')} <= {n('m')})", "bool"
    if p == "more_than":
        return f"({n('m')} < {n('t')})", "bool"
    if p == "exceeds":
        return f"({n('t')} < {n('m')})", "bool"
    if p == "at_most_value":
        return f"({n('m')} <= {n('t')})", "bool"
    if p == "sum_within":
        return f"({n('m')} + {n('t')} <= {n('z')})", "bool"
    if p == "sum_exceeds":
        return f"({n('z')} < {n('m')} + {n('t')})", "bool"
    if p == "not":
        return f"!{a('p')[0]}", "bool"
    if p == "aggregate":
        return f"sum({a('ns')[0]})", "num"
    if p == "all_of":
        return a("pm")
    if p == "holds_of":
        ie, isort = a("i")
        it = f"it{e.depth}"
        return f"{{ let {it} = {ie}; {gen(A['p'], e.with_item(it, isort))[0]} }}", "bool"
    if p in ("every", "no_such", "some_of", "the_first"):
        c, _ = a("c")
        it = f"it{e.depth}"
        body = gen(A["p"], e.with_item(it, item_sort(A["c"])))[0]
        fn = {"every": "all", "no_such": "!any", "some_of": "any", "the_first": "first"}[p]
        return f"{fn}({c}, |{it}| {body})", "bool"
    if p == "accepted":
        return ACCEPTED[e.op].format(a=ans()), "bool"
    raise Unsupported(f"no typed reading of Clausebook piece `{p}`")


def item_sort(c) -> str:
    """The sort of the items of a collection tree."""
    if isinstance(c, dict):
        if c.get("p") in ("l.transfers", "l.stopped_at"):
            return "transfer"
        if c.get("k") == "value":
            return "transfer" if c["type"] == "batch" else "num"
    return "num"


def frame(node, pre: Env, post: Env, unchanged: str, ref_args) -> str:
    """The content of a frame about ONE call (pieces.rs `frame_content`), as a Rust boolean expression."""
    f = node["p"]
    A = node.get("a") or {}

    def before(name):
        return gen(A[name], pre)

    def after(name):
        return gen(A[name], post)

    def num(pair, what):
        if pair[1] != "num":
            raise Unsupported(f"{f}: {what} is a {pair[1]}, not a number")
        return pair[0]
    if f == "always_answers":
        return "true"
    if f == "never_changes":
        return eq(after("m"), before("m"))
    if f == "changes_only":
        parts = A["c"]
        if parts.get("p") != "l.accounts":
            raise Unsupported(f"no part measure for {parts.get('p')}")
        lpre, lpost = gen(parts["a"]["l"], pre)[0], gen(parts["a"]["l"], post)[0]
        xs = before("xs")[0]
        return (f"({eq(after('c'), before('c'))} && {{ let xs = {xs}; all({before('c')[0]}, |k| has(xs, k) || bal_of({lpost}, k) == bal_of({lpre}, k)) }})")
    if f == "always":
        return before("c")[0]
    if f == "never":
        return f"!{before('c')[0]}"
    if f == "if_then":
        return f"(!{before('k')[0]} || {before('c')[0]})"
    if f == "only_if":
        return f"(!{before('c')[0]} || {before('k')[0]})"
    if f == "exactly_when":
        return f"({before('c')[0]} == {before('k')[0]})"
    if f == "rejected_unchanged":
        return f"(!{ACCEPTED[pre.op].format(a=pre.ans)} && {unchanged})"
    if f == "increases_by":
        return f"({num(after('m'), 'm')} == {num(before('m'), 'm')} + {num(before('t'), 't')})"
    if f == "decreases_by":
        return f"({num(after('m'), 'm')} + {num(before('t'), 't')} == {num(before('m'), 'm')})"
    if f == "becomes":
        return eq(after("m"), before("t"))
    if f == "result_is":
        return eq(before("a"), before("t"))
    if f == "result_at_most":
        return f"({num(before('a'), 'a')} <= {num(before('t'), 't')})"
    if f == "result_at_least":
        return f"({num(before('t'), 't')} <= {num(before('a'), 'a')})"
    if f == "at_most":
        return f"({num(after('m'), 'm')} <= {num(before('t'), 't')})"
    if f == "at_least":
        return f"({num(before('t'), 't')} <= {num(after('m'), 'm')})"
    if f == "each_at_most":
        ns = after("ns")
        if ns[1] != "list":
            raise Unsupported(f"{f}: ns is a {ns[1]}, not a collection of numbers")
        return f"{{ let bound = {num(before('t'), 't')}; all({ns[0]}, |n_| n_ <= bound) }}"
    if f in ("every_of", "none_of"):
        it = f"it{post.depth}"
        body = gen(A["p"], post.with_item(it, item_sort(A["c"])))[0]
        return f"{'all' if f == 'every_of' else '!any'}({after('c')[0]}, |{it}| {body})"
    if f == "within":
        return f"{{ let sup = {before('d')[0]}; all({after('c')[0]}, |i| has(sup, i)) }}"
    if f == "covers":
        return f"{{ let sup = {after('c')[0]}; all({before('d')[0]}, |i| has(sup, i)) }}"
    if f == "agrees_with":
        piece = A["r"]["p"]
        fresh, spre, inp, spost = ref_args
        return (f"match ref_{san(piece)}({fresh}, {spre}, {inp}) {{ None => false, Some((ra, rs)) => {pre.ans} == ra && "
                f"match &rs {{ Some(l) => same({spost}, &l.balances[..]), None => same({spost}, {spre}) }} }}")
    raise Unsupported(f"no typed reading of frame `{f}`")


def frame2(node, refs, op, a1: str, a2: str) -> str:
    """The content of a frame that compares TWO calls (pieces.rs `frame2_content`)."""
    def cls(ans):
        return gen(node["a"]["c"], Env(refs, {}, ans, op))[0]
    f = node["p"]
    if f == "monotone":
        return f"(!{cls(a1)} || {cls(a2)})"
    if f == "same_answer":
        return f"({a1} == {a2})"
    if f == "same_answer_if":
        return f"(!{cls(a1)} || {a1} == {a2})"
    raise Unsupported(f"no typed reading of two-run frame `{f}`")


class Plan:
    """Everything the three generated files need to know about one reading."""

    def __init__(self, trees: dict, rd: dict, n: int):
        self.rd, self.n, self.id = rd, n, rd["id"]
        self.ops = trees["ops"]
        self.built_from = trees["actor_built_from"]
        self.building = set(trees["building_measures"])
        self.vars = [(v["name"], v["type"]) for v in rd["vars"]]
        self.vtype = dict(self.vars)
        self.two = rd.get("run2") is not None
        self.width = 0
        self.pool = set()
        self.ledgers = []       # [(param name, var that builds it)]: one fresh ledger of the crate per unit, side and ledger actor
        self.batches = []       # [var]: batch variables handed to an operation (as the crate's own type)
        self.solved = {}        # actor variable -> ("var", name) | ("lit", text): a Given FIXES this actor
        self.twin = {}          # variable of the second call -> its counterpart of the first
        for v, t in self.vars:
            if t not in RUST_TY:
                raise Unsupported(f"variable {v} has type {t}")
        self.solve()
        self.body = self.check_body()

    # ---- what the Givens fix
    def solve(self):
        rd = self.rd
        actor_var = {a["ref"]: (a["var"], a["type"]) for a in rd["run1"]["actors"]}
        if not self.two:
            for u in rd["units"]:
                for c in u["conds"]:
                    numbers_in(c, self.pool)
                    if c.get("p") != "is":
                        continue
                    m, t = c["a"]["m"], c["a"]["t"]
                    if not (isinstance(m, dict) and m.get("p") in self.building and not m.get("per_actor")):
                        continue
                    who = next(iter(m["a"].values()))
                    leaf = next(iter(t["a"].values())) if isinstance(t, dict) and "p" in t and len(t.get("a") or {}) == 1 else None
                    if not (isinstance(who, dict) and who.get("k") == "actor" and isinstance(leaf, dict) and leaf.get("k") == "value"):
                        continue
                    var, atype = actor_var.get(who["ref"], (None, None))
                    if var is None or var in self.solved or leaf["type"] != self.built_from[atype]:
                        continue
                    if leaf.get("lit") is not None:
                        self.solved[var] = ("lit", leaf["lit"])
                    elif leaf.get("ref") in self.vtype and leaf["ref"] != var and len(rd["units"]) == 1:
                        self.solved[var] = ("var", leaf["ref"])
        for u in rd["units"]:
            for c in u["claims"]:
                numbers_in(c["node"], self.pool)
        for i in rd["run1"]["inputs"] + ((rd["run2"] or {}).get("inputs") or []):
            if i.get("lit"):
                self.pool.update(int(x) for x in re.findall(r"\d+", i["lit"]))
        if self.two:
            for a1, a2 in zip(rd["run1"]["actors"], rd["run2"]["actors"]):
                self.twin[a2["var"]] = a1["var"]
            for i1, i2 in zip(rd["run1"]["inputs"], rd["run2"]["inputs"]):
                if i1.get("var") and i2.get("var"):
                    self.twin[i2["var"]] = i1["var"]

    # ---- the reading at one point
    def side(self, run):
        refs = {v: (f"v_{san(v)}", t) for v, t in self.vars}
        for i in run["inputs"]:
            if i.get("ref") and i.get("var"):
                refs[i["ref"]] = (f"v_{san(i['var'])}", i["type"])
            elif i.get("ref") and i.get("lit") is not None:
                refs.pop(i["ref"], None)
        actors = {a["ref"]: (a["var"], a["type"]) for a in run["actors"]}
        return refs, actors

    def input_expr(self, i, k, lines):
        """An operation's input as the crate wants it, and as the typed readings want it (raw)."""
        if i.get("type") is None:
            return None, None
        t = i["type"]
        if i.get("var"):
            v = f"v_{san(i['var'])}"
            if t == "batch":
                if i["var"] not in self.batches:
                    self.batches.append(i["var"])
                return f"xb_{san(i['var'])}", v
            return v, v
        text = i["lit"]
        if t in ("amount", "index"):
            return f"{int(text)}u64", f"{int(text)}u64"
        if t == "transfer":
            e = lit_expr(t, text)[0]
            return e, e
        if t == "batch":
            name = f"lit_batch{len(lines)}"
            lines.append(f"    let {name}: Vec<Transfer> = mk_batch({lit_expr(t, text)[0]});")
            return f"&{name}[..]", lit_expr(t, text)[0]
        raise Unsupported(f"a literal input of type {t}")

    def run_code(self, u, k, s, run, refs, actors, lines, guard):
        """Rust for the unit's call(s) from side `s`: (name of the Option result, the names of the answer and of the states
        after, in the order of the unit's `state`, raw inputs)."""
        state = u["state"]
        cur, steps, raws, exs = [], [], [], []
        for j, name in enumerate(state):
            var, typ = actors[name]
            if typ == "ledger":
                pn = f"x{k}_{s}_{j}"
                self.ledgers.append((pn, var))
                cur.append(pn)
            else:
                cur.append(f"v_{san(var)}")
        for m, op in enumerate(u["ops"]):
            if u.get("tie") and m == 1:       # a tied sequence: the second call's input is what the tie makes of the first's
                ex, raw = f"tie_{san(u['tie'])}({exs[0]})", f"tie_{san(u['tie'])}({raws[0]})"
            else:
                ex, raw = self.input_expr(run["inputs"][m], m, lines)
            raws.append(raw)
            exs.append(ex)
            args = ", ".join(cur + ([ex] if ex is not None else []))
            outs = ["a"] + [f"s{j}" for j in range(len(state))]
            steps.append(f"let ({', '.join(outs)}) = {RUN_FN[op]}({args})?;")
            cur = outs[1:]
        r = f"r{k}_{s}"
        lines.append(f"    let {r} = if {guard} {{ (|| {{ {' '.join(steps)} Some((a, {', '.join(cur)})) }})() }} else {{ None }};")
        return r, raws, exs

    def check_body(self) -> str:
        rd = self.rd
        refs1, actors1 = self.side(rd["run1"])
        refs2, actors2 = self.side(rd["run2"]) if self.two else (None, None)
        lines, bits, holds, scoped = [], [], [], []

        def pre_actors(actors):
            return {name: f"v_{san(var)}" for name, (var, typ) in actors.items()}

        def post_actors(actors, state):
            out = {}
            for name, (var, typ) in actors.items():
                if name in state:
                    j = state.index(name)
                    out[name] = f"(&s{j}.balances[..])" if typ == "ledger" else f"(*s{j})"
                else:
                    out[name] = f"v_{san(var)}"         # a bystander: the operation does not touch it
            return out

        for k, u in enumerate(rd["units"]):
            op = u["ops"][-1]
            state = u["state"]
            lines.append(f"    // ---- unit {k}: {' then '.join(u['ops'])} on {', '.join(state)}")

            def scope(refs, actors, run):
                e = Env(refs, pre_actors(actors), None, op)
                parts = []
                if u.get("internal"):
                    i = run["inputs"][0]
                    parts.append(f"internal_{san(u['ops'][0])}({', '.join(e.actors[n_] for n_ in state)}, v_{san(i['var'])})")
                for c in u["conds"]:
                    ex, s = gen(c, e)
                    if s != "bool":
                        raise Unsupported("a Given that is not a condition")
                    parts.append(ex)
                return " && ".join(parts) or "true"
            sc = f"sc{k}"
            lines.append(f"    let {sc}: bool = {scope(refs1, actors1, rd['run1'])};")
            bits.append(sc)
            r1, raws1, exs1 = self.run_code(u, k, 1, rd["run1"], refs1, actors1, lines, sc)
            two_claims = [c for c in u["claims"] if c["runs"] == 2]
            rels = {}
            if two_claims:
                sc2 = f"sc{k}_2"
                lines.append(f"    let {sc2}: bool = {scope(refs2, actors2, rd['run2'])};")
                pv1 = pre_actors(actors1)[state[0]]
                pv2 = pre_actors(actors2)[state[0]]
                raw2 = self.input_expr(rd["run2"]["inputs"][0], 0, lines)[1]
                for c in two_claims:
                    piece = c["node"]["a"]["v"]["p"]
                    rels[c["index"]] = f"rel{c['index']}"
                    lines.append(f"    let rel{c['index']}: bool = var_{san(piece)}({pv1}, {raws1[0]}, {pv2}, {raw2});")
                r2, _, _ = self.run_code(u, k, 2, rd["run2"], refs2, actors2, lines, f"{sc} && {sc2} && ({' || '.join(rels.values())})")
            outs = ", ".join(["a"] + [f"s{j}" for j in range(len(state))])
            for c in u["claims"]:
                j = c["index"]
                if c["runs"] == 2:
                    bits.append(rels[j])
                    content = frame2(c["node"], refs1, op, "a1", "a2")
                    acc1, acc2 = ACCEPTED[op].format(a="a1"), ACCEPTED[op].format(a="a2")
                    lines.append(f"    let c{j}: bool = if {sc} && {rels[j]} && sc{k}_2 {{ holds_at2({calls_of(c['mods'])}, match (&{r1}, &{r2}) {{ "
                                 f"(Some(o1), Some(o2)) => {{ let (a1, a2) = (o1.0, o2.0); Some(({acc1}, {acc2}, {content})) }} _ => None }}) }} else {{ true }};")
                    scoped.append(f"({sc} && {rels[j]} && sc{k}_2)")
                else:
                    pre = Env(refs1, pre_actors(actors1), "a", op)
                    post = Env(refs1, post_actors(actors1, state), "a", op)
                    unchanged = " && ".join((f"same({post.actors[n_]}, {pre.actors[n_]})" if t == "ledger" else f"({post.actors[n_]} == {pre.actors[n_]})")
                                            for n_, (_, t) in actors1.items()) or "true"
                    ref_args = None
                    if c["node"]["p"] == "agrees_with":
                        # a fresh ledger of the crate with the state before the call, for a reference that is another operation
                        self.ledgers.append((f"xr{j}", actors1[state[0]][0]))
                        ref_args = (f"xr{j}", pre.actors[state[0]], exs1[-1], post.actors[state[0]])
                    content = frame(c["node"], pre, post, unchanged, ref_args)
                    lines.append(f"    let c{j}: bool = !{sc} || holds_at({calls_of(c['mods'])}, match &{r1} {{ None => None, Some(({outs})) => {{ let a = *a; "
                                 f"Some(({ACCEPTED[op].format(a='a')}, {content})) }} }});")
                    scoped.append(sc)
                bits.append(f"c{j}")
                holds.append(f"c{j}")
        self.width = len(bits)
        lines.append(f"    Pt {{ bits: [{', '.join(bits)}], scoped: {' || '.join(dict.fromkeys(scoped)) or 'false'}, holds: {' && '.join(holds) or 'true'} }}")
        return "\n".join(lines)

    # ---- signatures
    def params(self) -> list:
        """[(name, Rust type)] of check_<n>: every variable, then one ledger of the crate per unit / side / ledger actor,
        then every batch variable as the crate's own type."""
        out = [(f"v_{san(v)}", RUST_TY[t]) for v, t in self.vars]
        out += [(p, "Ledger") for p, _ in self.ledgers]
        out += [(f"xb_{san(v)}", "&[Transfer]") for v in self.batches]
        return out

    def check_fn(self) -> str:
        ps = ", ".join(f"{n}: {t}" for n, t in self.params())
        return (f"/// {self.id}\n#[allow(unused_variables, unused_parens, clippy::all)]\npub fn check_{self.n}({ps}) -> Pt<{self.width}> {{\n{self.body}\n}}\n")

    def source(self, var: str):
        """Where a variable's value comes from: ("free",) | ("var", other) | ("lit", text)."""
        return self.solved.get(var, ("free",))

    def uses(self) -> tuple:
        """(some variable is a list of balances, some variable is a batch): which sizes of the ladder matter."""
        free = [t for v, t in self.vars if self.source(v)[0] == "free"]
        return "balances" in free, "batch" in free


def plans(trees: dict) -> tuple:
    """([Plan], {reading id: why it has no typed reading})."""
    out, skipped = [], {}
    for n, rd in enumerate(trees["readings"]):
        try:
            out.append(Plan(trees, rd, n))
        except (Unsupported, KeyError) as e:
            skipped[rd["id"]] = str(e)
    return out, skipped


def checks_file(ps: list) -> str:
    return (HEAD + "// The reading of every compiled sentence at ONE point, as typed Rust over the per-piece readings of typed.rs.\n"
            "use crate::typed::*;\n\n" + "\n".join(p.check_fn() for p in ps))


def table_file(ps: list) -> str:
    """The property-test side: the variables of every reading and the glue from generated values to its check."""
    out = [HEAD + "// What the generic property-test runner (main.rs) needs to know about each reading.\n"
           "use crate::checks::*;\nuse crate::typed::*;\nuse crate::{GV, Rule, Src, Ty, Var};\n"]
    rows = []
    for p in ps:
        idx = {v: k for k, (v, _) in enumerate(p.vars)}
        get = {"amount": "num", "index": "num", "balances": "bal", "transfer": "tr", "batch": "batch"}
        lets = [f"    let xb_{san(v)} = mk_batch(g[{idx[v]}].batch());" for v in p.batches]
        args = [f"g[{idx[v]}].{get[t]}()" for v, t in p.vars]
        args += [f"mk_ledger(g[{idx[var]}].bal())" for _, var in p.ledgers]
        args += [f"&xb_{san(v)}[..]" for v in p.batches]
        out.append(f"fn call_{p.n}(g: &[GV]) -> (Vec<bool>, bool, bool) {{\n" + "\n".join(lets) + ("\n" if lets else "")
                   + f"    let p = check_{p.n}({', '.join(args)});\n    (p.bits.to_vec(), p.scoped, p.holds)\n}}\n")
        vs = []
        for v, t in p.vars:
            src = p.source(v)
            s = ("Src::Free" if src[0] == "free" else f"Src::SameAs({idx[src[1]]})" if src[0] == "var" else f"Src::Lit({json.dumps(src[1])})")
            if v in p.twin and src[0] == "free":
                s = f"Src::Twin({idx[p.twin[v]]})"
            vs.append(f"Var {{ name: {json.dumps(v)}, ty: Ty::{t.capitalize()}, src: {s} }}")
        rows.append(f"    Rule {{ id: {json.dumps(p.id)}, vars: &[{', '.join(vs)}], pool: &[{', '.join(str(x) + 'u64' for x in sorted(p.pool) if x < 2**64)}], call: call_{p.n} }},")
    out.append("pub static RULES: &[Rule] = &[\n" + "\n".join(rows) + "\n];\n")
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------- Kani

def rungs_of(p: Plan) -> list:
    """The rungs of the ladder that differ for this reading: [(label, accounts | None, transfers | None)]."""
    ub, ut = p.uses()
    if not ub and not ut:
        return [("no size bound", None, None)]
    out, seen = [], set()
    for a, b in LADDER:
        key = (a if ub else None, b if ut else None)
        if key in seen:
            continue
        seen.add(key)
        label = " and ".join(([f"up to {a} accounts"] if ub else []) + ([f"up to {b} transfer{'s' if b != 1 else ''}"] if ut else []))
        out.append((label, key[0], key[1]))
    return out


def harness_name(p: Plan, r: int) -> str:
    return f"k{p.n}_r{r}"


def kani_file(ps: list, only=None) -> tuple:
    """(Rust text, {harness name: {id, rung, accounts, transfers, layout}}). `layout` lists, in the order Kani draws them,
    the symbolic values of the harness: [(variable, type, size)], so a counterexample can be read back."""
    out = [HEAD + "// One bounded-model-checking harness per compiled reading and per rung of the size ladder. Every integer is fully\n"
           "// symbolic; a list of balances has at most A items and a batch at most B (the rung). `check_<n>` is the same generated\n"
           "// predicate the property test asserts.\nuse crate::checks::*;\nuse crate::typed::*;\n"]
    meta = {}
    for p in ps:
        if only is not None and p.id not in only:
            continue
        for r, (label, A, B) in enumerate(rungs_of(p)):
            name = harness_name(p, r)
            body, layout, expr = [], [], {}
            lits = []
            lits_in(p.rd["units"], lits)
            lits += [i["lit"] for run in (p.rd["run1"], p.rd.get("run2") or {}) for i in run.get("inputs", []) if i.get("lit")]
            longest = max([0] + [len(items(x)) for x in lits if x.strip().startswith("[")])
            for v, t in p.vars:
                s = san(v)
                src = p.source(v)
                if src[0] == "var":
                    continue
                if src[0] == "lit":
                    body.append(f"    let v_{s}: {RUST_TY[t]} = {lit_expr(t, src[1])[0]};" if t not in ("amount", "index")
                                else f"    let v_{s}: u64 = {int(src[1])}u64;")
                    expr[v] = None
                    continue
                if t in ("amount", "index"):
                    body.append(f"    let v_{s}: u64 = kani::any();")
                    layout.append((v, t, 1))
                elif t == "transfer":
                    body.append(f"    let v_{s}: T = kani::any();")
                    layout.append((v, t, 1))
                elif t == "balances":
                    body.append(f"    let a_{s}: [u64; {A}] = kani::any();\n    let n_{s}: usize = kani::any();\n    kani::assume(n_{s} <= {A});\n"
                                f"    let v_{s}: &[u64] = &a_{s}[..n_{s}];")
                    layout.append((v, t, A))
                    expr[v] = f"{{ let mut b = a_{s}.to_vec(); b.truncate(n_{s}); Ledger {{ balances: b }} }}"
                elif t == "batch":
                    body.append(f"    let a_{s}: [T; {B}] = kani::any();\n    let n_{s}: usize = kani::any();\n    kani::assume(n_{s} <= {B});\n"
                                f"    let v_{s}: &[T] = &a_{s}[..n_{s}];")
                    layout.append((v, t, B))
            for v, t in p.vars:
                src = p.source(v)
                if src[0] == "var":
                    body.append(f"    let v_{san(v)}: {RUST_TY[t]} = v_{san(src[1])};")
                    expr[v] = expr.get(src[1])
            args = [f"v_{san(v)}" for v, _ in p.vars]
            for _, var in p.ledgers:
                args.append(expr.get(var) or f"mk_ledger(v_{san(var)})")
            for v in p.batches:
                s = san(p.source(v)[1]) if p.source(v)[0] == "var" else san(v)
                body.append(f"    let xb_{san(v)} = a_{s}.map(|(from, to, amount)| Transfer {{ from, to, amount }});")
                args.append(f"&xb_{san(v)}[..n_{s}]")
            unwind = max([x for x in (A, B) if x is not None] + [longest, 1]) + 2
            out.append(f"/// {p.id}   [{label}]\n#[kani::proof]\n#[kani::unwind({unwind})]\nfn {name}() {{\n" + "\n".join(body)
                       + f"\n    let p = check_{p.n}({', '.join(args)});\n    assert!(p.holds, \"RULE\");\n}}\n")
            meta[name] = {"id": p.id, "rung": r, "label": label, "accounts": A, "transfers": B, "unwind": unwind, "layout": layout}
    return "\n".join(out), meta


def decode_playback(text: str, layout: list) -> dict | None:
    """Kani's concrete playback (`--concrete-playback=print`) -> {variable: literal text}. The playback lists one byte
    vector per symbolic value in the order the harness drew them; `layout` is that order."""
    vals = []
    for m in re.finditer(r"vec!\[([\d,\s]*)\]", text.split("let concrete_vals", 1)[-1]):
        bs = [int(x) for x in re.findall(r"\d+", m.group(1))]
        vals.append(int.from_bytes(bytes(bs), "little"))
    out, k = {}, 0

    def take():
        nonlocal k
        k += 1
        return vals[k - 1]
    try:
        for v, t, size in layout:
            if t in ("amount", "index"):
                out[v] = str(take())
            elif t == "transfer":
                f, to, a = take(), take(), take()
                out[v] = f"{f}->{to}:{a}"
            elif t == "balances":
                xs = [take() for _ in range(size)]
                n = take()
                out[v] = "[" + ", ".join(str(x) for x in xs[:n]) + "]"
            elif t == "batch":
                xs = [(take(), take(), take()) for _ in range(size)]
                n = take()
                out[v] = "[" + ", ".join(f"{f}->{to}:{a}" for f, to, a in xs[:n]) + "]"
    except IndexError:
        return None
    return out


def write_all(root, trees: dict, kani_only=None) -> dict:
    """Write the three generated files under <root>/evidence; returns what was generated (build/evidence_gen.json)."""
    ps, skipped = plans(trees)
    ev = root / "evidence"
    (ev / "src").mkdir(parents=True, exist_ok=True)
    (ev / "kani" / "src").mkdir(parents=True, exist_ok=True)
    (ev / "src" / "checks.rs").write_text(checks_file(ps))
    (ev / "src" / "table.rs").write_text(table_file(ps))
    text, meta = kani_file(ps, kani_only)
    (ev / "kani" / "src" / "harnesses.rs").write_text(text)
    info = {"ladder": LADDER, "readings": {p.id: {"n": p.n, "width": p.width, "vars": p.vars,
                                                  "fixed_by_givens": {v: list(s) for v, s in p.solved.items()},
                                                  "second_call_of": p.twin, "rungs": [list(r) for r in rungs_of(p)],
                                                  # plan node E2: the collections whose length no Given fixes (clausal/sizes.py)
                                                  "collections": dict(zip(("balances", "batch"), p.uses())),
                                                  "lines": len(p.body.splitlines())} for p in ps},
            "skipped": skipped, "harnesses": meta}
    (root / "build").mkdir(exist_ok=True)
    (root / "build" / "evidence_gen.json").write_text(json.dumps(info, indent=1, ensure_ascii=False))
    return info

#!/usr/bin/env python3
"""Cross-corpus table of the friction export (counts, timings, coverage). Reads the three
coverage.json / export_meta.json / verify_*.json files and writes out/corpus/friction/SUMMARY.md.
Descriptive only: it reports what the exporter produced, not an analysis of the claims."""
import json, os
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = os.path.join(REPO, 'out/corpus/friction')
CS = ['ns', 'carleson', 'pfr']
cov = {c: json.load(open(f'{F}/{c}/coverage.json')) for c in CS}
meta = {c: json.load(open(f'{F}/{c}/export_meta.json')) for c in CS}
chk = {c: json.load(open(f'{F}/{c}/verify_checks.json')) for c in CS}
ver = {c: json.load(open(f'{F}/{c}/verify_verdicts.json')) for c in CS}
cfg = json.load(open(os.path.join(REPO, 'bench/friction_families.json')))
side = cfg['side_condition_classes']
L = ['# Friction export: counts, timings, coverage\n',
     'Generated by `bench/friction_summary.py`. ns = machine-written (OpenAI Navier-Stokes/Euler); carleson, pfr = human-written. '
     f"Config version {cfg['version']} (`bench/friction_families.json`). Definitions: `README.md` in this folder.\n",
     '## Export\n', '| | ' + ' | '.join(CS) + ' |', '|---|' + '---|' * len(CS)]
def row(label, f):
    L.append(f'| {label} | ' + ' | '.join(str(f(c)) for c in CS) + ' |')
row('Lean', lambda c: meta[c]['leanVersion'])
row('theorems exported', lambda c: meta[c]['written'])
row('listed but not found', lambda c: len(meta[c]['theoremsUnresolved']))
row('statement failures', lambda c: meta[c]['stmtFail'])
row('proof-mass failures', lambda c: meta[c]['massFail'])
row('wall seconds (shards)', lambda c: f"{meta[c]['wallSeconds']} ({meta[c]['shards']})")
row('of which import, per shard (s)', lambda c: round(max(meta[c]['importMsPerShard']) / 1000))
row('sum of per-theorem time (s)', lambda c: round(meta[c]['sumTheoremMs'] / 1000))
row('theorems over 2 s', lambda c: meta[c]['theoremsOver2s'])
row('statementSize differs from earlier export', lambda c: chk[c]['statementSizeMismatch'])
row('proofSize differs from earlier export', lambda c: chk[c]['proofSizeMismatch'])
row('hand-checked theorems: agree / disagree', lambda c: f"{ver[c]['agree']} / {ver[c]['disagree']}")
L += ['', '## Statement telescopes\n', '| | ' + ' | '.join(CS) + ' |', '|---|' + '---|' * len(CS)]
for k in ['type', 'term', 'inst', 'hyp']:
    row(f'binders of kind {k}', lambda c: cov[c]['binderKinds'].get(k, 0))
row('Prop-valued binders (hypotheses + Prop instances)', lambda c: cov[c]['hypotheses']['n'])
for k in cfg['classes']:
    row(f"hypotheses % {k}{' (side)' if k in side else ''}", lambda c: cov[c]['hypotheses']['byClass'].get(k, [0, 0.0])[1])
row('**hypotheses % other, of which project-defined heads**', lambda c: f"{cov[c]['hypotheses']['otherPct']} ({cov[c]['hypotheses']['otherProjectDefinedPct']})")
row('**conclusions % other, of which project-defined heads**', lambda c: f"{cov[c]['conclusions']['otherPct']} ({cov[c]['conclusions']['otherProjectDefinedPct']})")
L += ['', '## Proof mass (share of distinct proof-term nodes)\n', '| | ' + ' | '.join(CS) + ' |', '|---|' + '---|' * len(CS)]
row('distinct nodes', lambda c: cov[c]['proofMass']['distinctNodes'])
row('outer: main %', lambda c: cov[c]['proofMass']['outer'].get('main', [0, 0.0])[1])
for k in side:
    row(f'outer: {k} %', lambda c: cov[c]['proofMass']['outer'].get(k, [0, 0.0])[1])
row('nodes in theorems whose own conclusion is a side-condition class %', lambda c: cov[c]['proofMass']['sideMassInTheoremsWhoseConclusionIsSidePct'])
for k in cfg['classes']:
    row(f'inner: {k} %', lambda c: cov[c]['proofMass']['inner'].get(k, [0, 0.0])[1])
row('**inner: other %, project-defined heads (first-reach audit) %**', lambda c: f"{cov[c]['proofMass']['innerOtherPct']} ({cov[c]['proofMass']['otherHeadMassFromProjectPredicatesPct']})")
row('inside a proof whose type mentions a cast function %', lambda c: cov[c]['proofMass']['castRegionPct'])
row('inside a proof whose type mentions indicator/restrict/support/cutoff %', lambda c: cov[c]['proofMass']['surgeryRegionPct'])
row('node kind: proof spine / data argument / instance argument %', lambda c: ' / '.join(str(v) for v in cov[c]['proofMass']['kindPct'].values()))
L += ['', '## Constants in proofs (DAG-unique uses, % of non-project uses)\n', '| | ' + ' | '.join(CS) + ' |', '|---|' + '---|' * len(CS)]
row('non-project uses', lambda c: cov[c]['proofConstants']['usesExt'])
row('project uses', lambda c: cov[c]['proofConstants']['usesProj'])
fams = sorted({k for c in CS for k in cov[c]['proofConstants']['extByFamily']}, key=lambda k: -cov['ns']['proofConstants']['extByFamily'].get(k, [0, 0])[1])
for k in fams:
    row(k, lambda c: cov[c]['proofConstants']['extByFamily'].get(k, [0, 0.0])[1])
row('**other_lemma as % of non-project lemma uses**', lambda c: cov[c]['proofConstants']['extOtherLemmaPctOfLemmaUses'])
open(f'{F}/SUMMARY.md', 'w').write('\n'.join(L) + '\n')

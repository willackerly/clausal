#!/usr/bin/env python3
"""deadcode: what a built Lean 4 project does not need for a chosen set of root declarations.

  deadcode.py <project.json> export                 read the built project with Lean (lean/Export.lean)
  deadcode.py <project.json> analyze [--no-scope]   classes 1-4, tables            -> out/deadcode/<name>/
  deadcode.py <project.json> control [-n 20]        negative control: delete USED declarations, expect failure
  deadcode.py <project.json> safe-delete --set dead|held|term [--sample N] [--run TAG] [--roots-only]
                                                    delete in a copy, rebuild, trace failures back to
                                                    declarations, restore them, repeat until the roots and
                                                    the project's other build targets build; then compare
                                                    the roots' axioms with the original build
  deadcode.py <project.json> build-all --run TAG    build the default (and extra) targets in the copy of a run
  deadcode.py <project.json> verify --run TAG       re-export the trimmed build and compare with the prediction
  deadcode.py <project.json> report                 REPORT.md from the JSON written by the other commands

Declarations, dependencies and tables come from Lean: the environment (Export.lean), the reference index
Lean writes next to every .olean (.ilean), Lean's parser run on the head of each declaration range, and,
when a build failure has to be traced back, Lean's own simp / instance traces.  Source text is cut at the
ranges Lean reports.  The places where text or a hand-written list decides something are listed in
README.md ("What is read, and from where").
"""

#!/usr/bin/env python3
"""report.py <project|planted>: writes out/reinvent/<project>/REPORT.md and summary.json from the stage files."""
import collections
import json
import os
import random
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
CONFIRMED = ('proved', 'proved under side condition')
ORDER = ['proved', 'proved under side condition', 'implication only', 'refuted', 'not proved', 'ill-typed', 'no result']


def staging(module):
    return any(x in (module or '') for x in ('ToMathlib', 'ForMathlib', '.Mathlib.'))


READING = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'reading.json')))
LABEL = {'R': 're-invention', 'U': 'use of the library (defined from it)', 'I': 'instance of a combinator',
         'C': 'coincidence', '?': 'unread'}
KEYS = 'RUIC?'


def reading(c):
    """Model reading of a confirmed pair, except 'U', which is mechanical: the alias rule can only fire when the
    project definition is the library constant applied to its own parameters."""
    if c.get('cls') == 'alias':
        return 'U'
    return READING['byD'].get(c['D'], READING['byL'].get(c['L'], '?'))


def main():
    p = sys.argv[1]
    out = os.path.join(REPO, 'out/reinvent', p)
    s1 = json.load(open(os.path.join(out, 'stage1.json')))
    f3 = os.path.join(out, 'stage3.jsonl')
    cands = [json.loads(l) for l in open(f3 if os.path.exists(f3) else os.path.join(out, 'stage2.jsonl'))]
    api = json.load(open(os.path.join(out, 'api_pairs.json'))) if os.path.exists(os.path.join(out, 'api_pairs.json')) else None
    W = []
    w = W.append
    w('# Re-invented library abstractions: %s\n' % p)
    w('Generated by `tools/reinvent/report.py` from `stage1.json`, `stage2.jsonl`, `stage3.jsonl`, `api_pairs.json` '
      'in this directory. Library: Mathlib (the project\'s own pinned copy). Every "proved" below is a theorem '
      'added through the Lean kernel in the project\'s built environment; axioms were collected for each. '
      'The detector\'s rules were changed after its first full run on ns and no commit freezes them, so these '
      'results are exploratory. Statements are shown as Lean prints them; a few do not re-elaborate as printed '
      'because the printer drops an implicit argument or a coercion\'s source type.\n')
    w('## Funnel\n')
    w('| stage | count |\n|---|---|')
    for k, v in s1['funnel'].items():
        w('| 1 · %s | %s |' % (k.strip(), v))
    vc = collections.Counter(c['verdict'] for c in cands)
    for v in ORDER:
        if vc[v]:
            w('| 2 · candidate pairs: %s | %d |' % (v, vc[v]))
    confD = {c['D'] for c in cands if c['verdict'] in CONFIRMED}
    w('| 2 · distinct project definitions with a kernel-checked equivalence | %d |' % len(confD))
    # a definition found only by unfolding another confirmed project definition is not a separate notion
    via = {}
    for c in cands:
        if c.get('primary') or (c['verdict'] in CONFIRMED and not any(x.get('primary') for x in cands)):
            v = [x for x in c.get('unfold', []) if x != c['D'] and x in confD]
            if v:
                via[c['D']] = v[0]
    w('| 2 · of those, defined from another confirmed project definition (found by unfolding it) | %d |' % len(via))
    w('| 2 · of those, the library constant applied to the definition\'s own parameters (alias rule: use of the library) | %d |'
      % len({c['D'] for c in cands if c['verdict'] in CONFIRMED and c.get('cls') == 'alias' and
             (c.get('primary') or not any(x.get('primary') for x in cands))}))
    nonstd = [c for c in cands if c['verdict'] in CONFIRMED and c.get('stdAxioms') is False]
    w('| 2 · confirmed equivalences depending on a non-standard axiom | %d |' % len(nonstd))
    if any('n_mapped' in c for c in cands):
        w('| 1c · candidate pairs with at least one project theorem mapping to a library theorem | %d |'
          % sum(1 for c in cands if c.get('n_mapped')))
        w('| 1c · of those, confirmed at stage 2 | %d |' % sum(1 for c in cands if c.get('n_mapped') and c['verdict'] in CONFIRMED))
    if api:
        w('| 1c · pairs proposed by holed statement signatures alone | %d (project predicates with theorems: %d) |'
          % (api['n_pairs'], api['project_predicates_with_theorems']))
        w('| 1c · of those, also a shape or wrapper candidate / confirmed | %d / %d |' % (api['n_also_shape'], api['n_confirmed']))
    prim = [c for c in cands if c.get('primary')]
    if prim:
        tot = collections.Counter()
        for c in prim:
            for k, v in c['cost'].items():
                tot[k] += v
        nd = sum(len(c['derive']) for c in prim)
        ok = sum(1 for c in prim for d in c['derive'] if d['status'] == 'derived')
        w('| 3 · project theorems whose statement mentions a confirmed definition | %d (%d source lines, proof size %d) |'
          % (tot['lemmas_about_D'], tot['lemmas_about_D_lines'], tot['lemmas_about_D_proof_size']))
        w('| 3 · of those, statement is an instance of a library theorem after substitution | %d (%d source lines, proof size %d) |'
          % (tot['mapped'], tot['mapped_lines'], tot['mapped_proof_size']))
        w('| 3 · sampled mapped theorems re-derived in Lean from the library theorem | %d of %d |' % (ok, nd))
        w('| 3 · project theorems that use a confirmed definition (statement or proof, direct; summed per definition) | %d |' % tot['users'])
    w('')
    w('Confirmed pairs by rule and class:\n')
    w('| rule | class | pairs | proved | under side condition | implication only | not proved | ill-typed |\n|---|---|---|---|---|---|---|---|')
    g = collections.defaultdict(collections.Counter)
    for c in cands:
        g[(c['rule'], c['cls'])][c['verdict']] += 1
    for k in sorted(g):
        x = g[k]
        w('| %s | %s | %d | %d | %d | %d | %d | %d |' % (k[0], k[1], sum(x.values()), x['proved'],
                                                    x['proved under side condition'], x['implication only'],
                                                    x['not proved'] + x['refuted'] + x['no result'], x['ill-typed']))
    tc = collections.Counter(c['tactic'] for c in cands if c['verdict'] in CONFIRMED)
    w('\nPortfolio entry that closed each confirmed pair: ' + ', '.join('%s %d' % kv for kv in tc.most_common()) + '.\n')

    def row(c):
        cost = c.get('cost', {})
        return '| `%s` | %s | `%s` | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            c['D'], c['Dkind'], c['L'], LABEL[reading(c)] + ('; defined from `%s`' % via[c['D']] if c['D'] in via else ''), c['verdict'] + (' (staging folder)' if staging(c['module']) else ''),
            '; '.join('`%s`' % s for s in c['sides']) if c['verdict'] == 'proved under side condition' else '—',
            c['tactic'], cost.get('lemmas_about_D', ''), cost.get('mapped', ''), cost.get('mapped_lines', ''),
            cost.get('users', ''))
    w('## Confirmed pairs (one library notion per project definition)\n')
    show = prim if prim else [c for c in cands if c['verdict'] in CONFIRMED]
    show.sort(key=lambda c: (-c.get('cost', {}).get('users', 0), c['D']))
    rc = collections.Counter(reading(c) for c in show)
    w('Reading by a model, by library notion (`tools/reinvent/reading.json`; not evidence): ' +
      ', '.join('%s %d' % (LABEL[k], rc[k]) for k in KEYS if rc[k]) + '. The detector does not use the reading. '
      '"Use of the library" is not a reading: it is every pair found by the alias rule.\n')
    if prim:
        w('| reading (model) | definitions | thms about D | lines | mapped | users |\n|---|---|---|---|---|---|')
        for k in KEYS:
            xs = [c for c in show if reading(c) == k]
            if xs:
                w('| %s | %d | %d | %d | %d | %d |' % (LABEL[k], len(xs), sum(c['cost']['lemmas_about_D'] for c in xs),
                                                 sum(c['cost']['lemmas_about_D_lines'] for c in xs),
                                                 sum(c['cost']['mapped'] for c in xs), sum(c['cost']['users'] for c in xs)))
        w('')
    w('%d definitions. Columns: theorems whose statement mentions D; of those, mapped to a library theorem; source lines of the mapped ones; project theorems using D.\n' % len(show))
    w('| project definition | kind | library notion | reading (model) | verdict | side condition | closed by | thms about D | mapped | mapped lines | users |\n|---|---|---|---|---|---|---|---|---|---|---|')
    for c in show[:400]:
        w(row(c))
    if len(show) > 400:
        w('\n(%d more in `stage3.jsonl`.)' % (len(show) - 400))
    w('\n## The ten most consequential cases\n')
    w('Ranked by the number of project theorems that use the definition, then by theorems about it.\n')
    top = sorted(show, key=lambda c: (-c.get('cost', {}).get('users', 0), -c.get('cost', {}).get('lemmas_about_D', 0), c['D']))[:10]
    for i, c in enumerate(top, 1):
        cost = c.get('cost', {})
        w('**%d. `%s`** (%s, `%s`) — library notion `%s`, %s, rule %s / %s; model reading: %s%s.' % (
            i, c['D'], c['Dkind'], c['module'], c['L'], c['verdict'], c['rule'], c['cls'], LABEL[reading(c)],
            '; defined from `%s`, which is also confirmed, so not a separate finding' % via[c['D']] if c['D'] in via else ''))
        if c['verdict'] == 'proved under side condition':
            w('\nSide condition: ' + '; '.join('`%s`' % x for x in c['sides']))
        w('\n```lean\n-- signature of the project definition\n%s\n-- kernel-checked statement (`%s`, closed by `%s`)\n%s\n```' % (
            c.get('pp', ''), c.get('thm'), c.get('tactic'), c.get('stmt')))
        if cost:
            w('Used by %d project theorems (%d in the statement); %d theorems are about it (%d lines, proof size %d); %d map to a library theorem (%d lines, proof size %d).' % (
                cost['users'], cost['statement_users'], cost['lemmas_about_D'], cost['lemmas_about_D_lines'],
                cost['lemmas_about_D_proof_size'], cost['mapped'], cost['mapped_lines'], cost['mapped_proof_size']))
        for d in c.get('derive', []):
            w('- `%s` from `%s`: %s%s' % (d['lemma'], d['lib'], d['status'], (' (' + d['tactic'] + ')') if d.get('tactic') else ''))
        w('')
    rtop = [c for c in sorted(show, key=lambda c: (-c.get('cost', {}).get('users', 0), c['D'])) if reading(c) == 'R'][:10]
    if rtop:
        w('### The ten most used among those read as re-inventions (model reading)\n')
        w('| project definition | library notion | users | thms about D | their lines | mapped |\n|---|---|---|---|---|---|')
        for c in rtop:
            cost = c.get('cost', {})
            w('| `%s` | `%s` | %s | %s | %s | %s |' % (c['D'], c['L'], cost.get('users', ''), cost.get('lemmas_about_D', ''),
                                                 cost.get('lemmas_about_D_lines', ''), cost.get('mapped', '')))
        w('')
    ef = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'planted', 'expected.json')
    if p == 'planted' and os.path.exists(ef):
        exp = {k: v for k, v in json.load(open(ef)).items() if not k.startswith('_')}
        w('## Controls against their expected outcome\n')
        w('Expected outcomes are in `tools/reinvent/planted/expected.json`. Neither author\'s controls are blind: '
          'the reviewer\'s were written after reading the matcher. "Shown" is the library notion the report shows for '
          'the definition; "intended" is the notion the control was written to equal.\n')
        w('| control | author | expected | outcome | shown | intended | as expected |\n|---|---|---|---|---|---|---|')
        tally = collections.defaultdict(lambda: [0, 0])
        primD = {c['D']: c for c in show}
        for D, (who, kind, want) in exp.items():
            mine = [c for c in cands if c['D'] == D]
            c = primD.get(D)
            if c:
                outcome, shown = c['verdict'], c['L']
            elif mine:
                vs = [x['verdict'] for x in mine]
                outcome = next((v for v in ORDER if v in vs), vs[0])
                shown = '—'
            else:
                outcome, shown = 'no candidate', '—'
            confirmed_any = any(x['verdict'] in CONFIRMED for x in mine)
            confirmed_want = any(x['verdict'] in CONFIRMED and x['L'] == want for x in mine)
            ok = (confirmed_want if kind == 'positive' else not confirmed_any if kind == 'negative' else confirmed_any)
            note = 'yes' if ok else 'no'
            if kind == 'positive' and ok and shown != want:
                note = 'yes, but another notion is shown'
            tally[(who, kind)][0] += ok
            tally[(who, kind)][1] += 1
            w('| `%s` | %s | %s | %s | %s | %s | %s |' % (D, who, kind, outcome, '`%s`' % shown if shown != '—' else shown,
                                                     '`%s`' % want if want else '—', note))
        w('')
        w('Tally: ' + '; '.join('%s %s %d of %d as expected' % (k[0], k[1], v[0], v[1]) for k, v in sorted(tally.items())) + '.\n')
    w('## Candidates not confirmed\n')
    rej = [c for c in cands if c['verdict'] not in CONFIRMED and c['D'] not in confD]
    w('%d pairs over %d definitions that have no confirmed pair. First 40 by pattern coverage:\n' % (len(rej), len({c['D'] for c in rej})))
    w('| project definition | library notion | rule / class | coverage | verdict |\n|---|---|---|---|---|')
    for c in sorted(rej, key=lambda c: (-c['cov'], c['D']))[:40]:
        w('| `%s` | `%s` | %s / %s | %.2f | %s |' % (c['D'], c['L'], c['rule'], c['cls'], c['cov'], c['verdict']))
    if api and api['pairs']:
        w('\n## Pairs proposed by statement signatures alone (top 25)\n')
        w('No argument correspondence is derived for these, so they were not sent to stage 2 unless they are also shape or wrapper candidates.\n')
        w('| project predicate | library predicate | theorems matched | theorems about D | also shape/wrapper candidate | confirmed |\n|---|---|---|---|---|---|')
        for a in api['pairs'][:25]:
            w('| `%s` | `%s` | %d | %d | %s | %s |' % (a['D'], a['L'], a['matched'], a['about_D'],
                                                    'yes' if a['also_shape_candidate'] else 'no', 'yes' if a['confirmed'] else 'no'))
    open(os.path.join(out, 'REPORT.md'), 'w').write('\n'.join(W) + '\n')
    # seeded samples for the precision reading
    rnd = random.Random(20261110)
    conf = sorted([c for c in cands if c['verdict'] in CONFIRMED], key=lambda c: c['id'])
    rejs = sorted(rej, key=lambda c: c['id'])
    samp = dict(confirmed=[dict(id=c['id'], D=c['D'], L=c['L'], reading=LABEL[reading(c)], stmt=c['stmt'], pp=c['pp'], rule=c['rule'], cls=c['cls'])
                           for c in rnd.sample(conf, min(15, len(conf)))],
                rejected=[dict(id=c['id'], D=c['D'], L=c['L'], verdict=c['verdict'], stmt=c.get('stmt'), msg=c.get('msg'), pp=c['pp'],
                               rhs=c['rhs']) for c in rnd.sample(rejs, min(15, len(rejs)))])
    json.dump(samp, open(os.path.join(out, 'reading_sample.json'), 'w'), indent=1, ensure_ascii=False)
    json.dump(dict(project=p, funnel=s1['funnel'], verdicts=dict(vc), confirmed_definitions=len(confD),
                   reading_all={LABEL[k]: v for k, v in collections.Counter(reading(c) for c in show).items()},
                   reading_sample=dict(collections.Counter(x['reading'] for x in samp['confirmed'])),
                   cost_by_reading={LABEL[k]: dict(definitions=len([c for c in show if reading(c) == k]),
                                                   thms=sum(c.get('cost', {}).get('lemmas_about_D', 0) for c in show if reading(c) == k),
                                                   lines=sum(c.get('cost', {}).get('lemmas_about_D_lines', 0) for c in show if reading(c) == k),
                                                   mapped=sum(c.get('cost', {}).get('mapped', 0) for c in show if reading(c) == k),
                                                   users=sum(c.get('cost', {}).get('users', 0) for c in show if reading(c) == k))
                                    for k in KEYS},
                   defined_from_another_confirmed=via,
                   distinct_notions=len(confD) - len(via),
                   by_rule={'%s/%s' % k: dict(v) for k, v in g.items()}), open(os.path.join(out, 'summary.json'), 'w'),
              indent=1, ensure_ascii=False)
    print(p, dict(vc), 'confirmed D', len(confD))


if __name__ == '__main__':
    main()
